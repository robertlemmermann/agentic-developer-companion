// Hooks: one intermediate form (IR), parsed from and rendered to each host's file.

/**
 * Parse a hooks file into `{ entries[], dropped[], notes[] }`. Entries carry a canonical
 * PascalCase event (or a Copilot-only camel event), a matcher in Claude tool names, and
 * either `exec {program, args}` or shell strings (`posix`, `windows` + `windowsShell`).
 */
export function parseHookConfig(text, host, file = 'hooks.json') {
  const dropped = [];
  const notes = [];
  let doc;
  try { doc = JSON.parse(stripBom(String(text))); } catch (err) { throw usageError(`${file}: not valid JSON (${err.message})`); }
  const hooks = doc && typeof doc === 'object' ? doc.hooks : null;
  if (!hooks || typeof hooks !== 'object') return { entries: [], dropped, notes: [`${file} has no "hooks" object`], version: doc?.version ?? null };
  const entries = [];
  for (const [evKey, list] of Object.entries(hooks)) {
    let event = null;
    let camel = false;
    if (host === 'copilot' && COPILOT_EVENT_TO_PASCAL[evKey]) { event = COPILOT_EVENT_TO_PASCAL[evKey]; camel = true; }
    else if (host === 'copilot' && COPILOT_ONLY_EVENTS.includes(evKey)) { event = evKey; camel = true; }
    else if (CLAUDE_EVENTS.includes(evKey) || CODEX_EVENTS.includes(evKey)) event = evKey;
    if (!event) { dropped.push({ file, field: `hooks.${evKey}`, reason: `unknown ${host} hook event` }); continue; }
    if (!Array.isArray(list)) { dropped.push({ file, field: `hooks.${evKey}`, reason: 'event value is not an array' }); continue; }
    for (const item of list) {
      if (!item || typeof item !== 'object') continue;
      const groupMatcher = item.matcher ?? null;
      const handlers = Array.isArray(item.hooks) ? item.hooks : [item];
      for (const h of handlers) {
        if (!h || typeof h !== 'object') continue;
        const entry = { event, camel, matcher: null, type: h.type || 'command', exec: null, posix: null, windows: null, windowsShell: null,
          timeout: null, cwd: null, env: null, extra: {}, source: host };
        const rawMatcher = h.matcher ?? groupMatcher;
        const table = host === 'copilot' && camel ? COPILOT_TOOL_TO_CANON : host === 'codex' ? CODEX_TOOL_TO_CANON : {};
        const tm = translateMatcher(rawMatcher, { ...Object.fromEntries(CLAUDE_TOOLS.map((t) => [t, t])), ...table });
        entry.matcher = tm.matcher;
        if (entry.type !== 'command') {
          dropped.push({ file, field: `hooks.${evKey}[].type`, value: entry.type, reason: `"${entry.type}" handlers are not ported (only command hooks)` });
          continue;
        }
        if (host === 'copilot') {
          if (Array.isArray(h.args) && h.exec) entry.exec = { program: String(h.exec), args: h.args.map(String) };
          else if (h.exec) entry.exec = { program: String(h.exec), args: [] };
          entry.posix = h.bash ?? (h.command && !h.exec ? h.command : null) ?? null;
          entry.windows = h.powershell ?? (h.command && !h.exec ? h.command : null) ?? null;
          entry.windowsShell = entry.windows ? 'powershell' : null;
          if (!entry.exec && !entry.posix && h.command && Array.isArray(h.args)) entry.exec = { program: String(h.command), args: h.args.map(String) };
          entry.timeout = h.timeoutSec ?? h.timeout ?? null;
          entry.cwd = h.cwd ?? null;
          entry.env = h.env && typeof h.env === 'object' ? h.env : null;
          for (const k of ['windows', 'linux', 'osx', 'hookSpecificOutput']) {
            if (k in h) dropped.push({ file, field: `hooks.${evKey}[].${k}`, reason: 'VS Code Local-harness key; Copilot CLI and the cloud agent ignore it' });
          }
          if (h.command && (h.bash || h.powershell)) notes.push(`${file}: an entry has both "command" and bash/powershell; bash/powershell win`);
        } else if (host === 'claude') {
          if (Array.isArray(h.args)) entry.exec = { program: String(h.command ?? ''), args: h.args.map(String) };
          else if (h.shell === 'powershell') { entry.windows = h.command ?? null; entry.windowsShell = 'powershell'; entry.extra.shellAll = 'powershell'; }
          else entry.posix = h.command ?? null;
          entry.timeout = h.timeout ?? null;
          for (const k of ['async', 'asyncRewake', 'onFailure', 'if', 'statusMessage', 'once']) if (k in h) entry.extra[k] = h[k];
        } else {
          entry.posix = h.command ?? null;
          entry.windows = h.commandWindows ?? h.command_windows ?? null;
          entry.windowsShell = entry.windows ? 'cmd' : null;
          entry.timeout = h.timeout ?? null;
          for (const k of ['async', 'statusMessage', 'additionalContextLimit']) if (k in h) entry.extra[k] = h[k];
        }
        normalizeHookEntry(entry);
        if (!entry.exec && !entry.posix && !entry.windows) {
          dropped.push({ file, field: `hooks.${evKey}[]`, reason: 'entry has no command' });
          continue;
        }
        if (tm.regex) entry.extra.matcherRegex = true;
        entries.push(entry);
      }
    }
  }
  return { entries, dropped, notes, version: doc.version ?? null };
}

/** Collapse shell strings that are plain program invocations into `exec` (portable everywhere). */
function normalizeHookEntry(entry) {
  if (entry.exec) return entry;
  const p = entry.posix ? splitSimpleCommand(entry.posix) : null;
  const w = entry.windows ? splitSimpleCommand(entry.windows) : null;
  const same = (a, b) => a && b && a.length === b.length && a.every((x, i) => x === b[i]);
  if (p && (!entry.windows || same(p, w))) { entry.exec = { program: p[0], args: p.slice(1) }; entry.posix = null; entry.windows = null; entry.windowsShell = null; }
  return entry;
}

const SCRIPT_EXT = /\.(mjs|cjs|js|ts|py|sh|ps1|rb|pl)$/i;

function relativeArg(arg) {
  return !/^[-$/~\\]/.test(arg) && !/^[A-Za-z]:/.test(arg) && !/^[a-z]+:\/\//i.test(arg) && (arg.includes('/') || SCRIPT_EXT.test(arg));
}

/**
 * Rewrite script paths between Claude's `${CLAUDE_PROJECT_DIR}` and repo-relative paths.
 * `claude` prefixes relative scripts (exec form); `claude-repo` and the other hosts keep them relative.
 */
function rebaseArgs(args, target, notes) {
  return args.map((a) => {
    if (target !== 'claude' && /^\$\{CLAUDE_PROJECT_DIR\}\//.test(a)) {
      notes.add('Paths under ${CLAUDE_PROJECT_DIR} became repository-relative; the hook must run from the repository root.');
      return a.replace(/^\$\{CLAUDE_PROJECT_DIR\}\//, '');
    }
    if (target === 'claude' && relativeArg(a)) return `\${CLAUDE_PROJECT_DIR}/${a.replace(/^\.\//, '')}`;
    return a;
  });
}

function copilotGuard(entry, bash, ps) {
  if (!entry.exec || /[/\\]/.test(entry.exec.program)) return { bash, ps };
  const prog = entry.exec.program;
  return {
    bash: `command -v ${prog} >/dev/null 2>&1 && ${bash} || echo {}`,
    ps: `if (Get-Command ${prog} -ErrorAction SilentlyContinue) { $o = ${ps.startsWith('& ') ? ps : `& ${ps}`} 2>$null; if ($LASTEXITCODE -eq 0 -and $o) { $o } else { '{}' } } else { '{}' }; exit 0`,
  };
}

/**
 * Render IR entries for a host. Returns `{ doc, dropped[], manual[] }`; `doc` is the JSON
 * object for `.github/hooks/*.json` (copilot), the `hooks` block of `.claude/settings.json`
 * (claude, wrapped as `{hooks}`), or `.codex/hooks.json` (codex).
 * `opts.guard` adds the missing-runtime guard (§7.7) to Copilot preToolUse entries.
 */
export function renderHookConfig(entries, target, { file = 'hooks', guard = false, pluginRoot = null } = {}) {
  const dropped = [];
  const manual = new Set();
  const notes = new Set();
  const crossHost = entries.some((e) => e.source !== target);
  if (target === 'copilot') {
    const hooks = {};
    for (const e of entries) {
      const ev = PASCAL_TO_COPILOT_EVENT[e.event] || (COPILOT_ONLY_EVENTS.includes(e.event) ? e.event : null);
      if (!ev) { dropped.push({ file, field: `hooks.${e.event}`, reason: 'Copilot has no equivalent event' }); continue; }
      const out = { type: 'command' };
      if (e.exec) {
        let argv = [e.exec.program, ...rebaseArgs(e.exec.args, 'copilot', notes)];
        if (pluginRoot) argv = argv.map((a) => a.replace(/\$\{CLAUDE_PLUGIN_ROOT\}/g, '${PLUGIN_ROOT}'));
        let bash = joinPosix(argv);
        let ps = joinPowerShell(argv);
        if (guard && ev === 'preToolUse') ({ bash, ps } = copilotGuard(e, bash, ps));
        out.bash = bash;
        out.powershell = ps;
      } else {
        if (e.posix) out.bash = e.posix;
        if (e.windows && e.windowsShell === 'powershell') out.powershell = e.windows;
        else if (e.windows && e.windowsShell === 'cmd') { out.powershell = `cmd /c ${e.windows}`; manual.add(`Check the PowerShell command of the ${ev} hook: it wraps the Codex cmd.exe command with "cmd /c".`); }
        if (!out.bash) manual.add(`Write a bash command for the ${ev} hook; the cloud agent runs only bash/command.`);
        if (!out.powershell) manual.add(`Write a PowerShell command for the ${ev} hook; Copilot on Windows runs the powershell field.`);
      }
      if (e.cwd) out.cwd = e.cwd;
      else if (pluginRoot && ev === 'preToolUse') out.cwd = '${PLUGIN_ROOT}';
      if (e.env) out.env = e.env;
      out.timeoutSec = e.timeout ?? 30;
      if (Number(out.timeoutSec) > 30) notes.add(`The ${ev} hook keeps a ${out.timeoutSec} s timeout; Copilot guidance and lint expect at most 30 s.`);
      if (e.matcher && TOOL_EVENTS.includes(e.event)) {
        const tm = e.extra.matcherRegex ? { matcher: e.matcher, unknown: [] } : translateMatcher(e.matcher, CANON_TO_COPILOT_TOOL);
        out.matcher = tm.matcher;
        if (tm.unknown.length) manual.add(`Matcher tool names without a Copilot equivalent were kept as-is: ${tm.unknown.join(', ')}.`);
      }
      for (const k of Object.keys(e.extra)) {
        if (k === 'matcherRegex') continue;
        dropped.push({ file, field: k, value: e.extra[k], reason: `Copilot command hooks have no "${k}"` });
      }
      (hooks[ev] ||= []).push(out);
    }
    if (crossHost) manual.add('Hook handlers must print Copilot\'s output shape: top-level additionalContext / permissionDecision / decision (no hookSpecificOutput).');
    return { doc: { version: 1, hooks }, dropped, manual: [...manual], notes: [...notes] };
  }
  const events = target === 'claude' ? CLAUDE_EVENTS : CODEX_EVENTS;
  const hooks = {};
  for (const e of entries) {
    if (!events.includes(e.event)) { dropped.push({ file, field: `hooks.${e.event}`, reason: `${target === 'claude' ? 'Claude Code' : 'Codex'} has no ${e.event} event` }); continue; }
    const h = { type: 'command' };
    if (target === 'claude') {
      if (e.exec && pluginRoot) {
        // Plugin hooks: exec form with ${CLAUDE_PLUGIN_ROOT} (Claude's own recommendation).
        h.command = e.exec.program;
        h.args = rebaseArgs(e.exec.args, 'claude', notes).map((a) => a.replace(/^\$\{CLAUDE_PROJECT_DIR\}\//, '${CLAUDE_PLUGIN_ROOT}/').replace(/\$\{PLUGIN_ROOT\}/g, '${CLAUDE_PLUGIN_ROOT}'));
      } else if (e.exec) {
        // Repository settings: Copilot CLI and VS Code run these hooks too, and their handling of
        // exec form is undocumented, so one shell string valid in sh, Git Bash and PowerShell.
        // ${CLAUDE_PROJECT_DIR} is not (PowerShell reads it as an unset variable, and Copilot
        // does not set it), so script paths stay repository-relative.
        h.command = joinPosix([e.exec.program, ...rebaseArgs(e.exec.args, 'claude-repo', notes)]);
        if (e.exec.args.some(relativeArg)) manual.add('Repository hooks in .claude/settings.json use repository-relative script paths (Copilot runs them too, in bash and PowerShell): start Claude Code and Copilot from the repository root.');
      } else if (e.posix) {
        h.command = e.posix;
        if (e.windows && e.windows !== e.posix) dropped.push({ file, field: 'powershell/commandWindows', value: e.windows, reason: 'Claude Code runs one command per hook (Git Bash on Windows when installed, else PowerShell)' });
      } else if (e.windows) {
        h.command = e.windows;
        h.shell = 'powershell';
        if (e.windowsShell === 'cmd') manual.add(`The ${e.event} hook only had a cmd.exe command; check it under PowerShell or add a bash command.`);
        else manual.add(`The ${e.event} hook only had a PowerShell command; Claude Code now runs it with shell: powershell on every OS.`);
      }
      if (e.timeout != null) h.timeout = Number(e.timeout);
      for (const [k, v] of Object.entries(e.extra)) {
        if (k === 'matcherRegex' || k === 'shellAll') continue;
        if (['async', 'asyncRewake', 'onFailure', 'if', 'statusMessage', 'once'].includes(k)) h[k] = v;
        else dropped.push({ file, field: k, value: v, reason: `Claude Code hooks have no "${k}"` });
      }
    } else {
      if (e.exec) {
        const argv = [e.exec.program, ...rebaseArgs(e.exec.args, 'codex', notes)];
        h.command = joinPosix(argv);
        h.commandWindows = joinCmd(argv);
      } else {
        if (e.posix) h.command = e.posix;
        if (e.windows && e.windowsShell === 'cmd') h.commandWindows = e.windows;
        else if (e.windows) {
          const simple = splitSimpleCommand(e.windows);
          h.commandWindows = simple ? joinCmd(simple) : `pwsh -NoProfile -Command ${JSON.stringify(e.windows)}`;
          if (!simple) manual.add(`Check the Windows command of the ${e.event} hook: Codex runs commandWindows under cmd.exe, so the PowerShell command was wrapped in pwsh -Command.`);
        }
        if (!h.command && h.commandWindows) { h.command = h.commandWindows; manual.add(`Write a POSIX command for the ${e.event} hook (only a Windows command existed).`); }
        if (!h.commandWindows) manual.add(`Add commandWindows to the ${e.event} hook if Windows users run Codex.`);
      }
      if (e.timeout != null) h.timeout = Number(e.timeout);
      if (e.cwd) dropped.push({ file, field: 'cwd', value: e.cwd, reason: 'Codex hooks have no cwd' });
      if (e.env) dropped.push({ file, field: 'env', value: Object.keys(e.env).join(','), reason: 'Codex hooks have no env' });
      for (const [k, v] of Object.entries(e.extra)) {
        if (k === 'matcherRegex' || k === 'shellAll') continue;
        if (['async', 'statusMessage', 'additionalContextLimit'].includes(k)) h[k] = v;
        else dropped.push({ file, field: k, value: v, reason: `Codex hooks have no "${k}"` });
      }
    }
    if (target === 'claude' && (e.cwd || e.env)) {
      if (e.cwd) dropped.push({ file, field: 'cwd', value: e.cwd, reason: 'Claude Code hooks have no cwd' });
      if (e.env) dropped.push({ file, field: 'env', value: Object.keys(e.env).join(','), reason: 'Claude Code hooks have no env' });
    }
    let matcher = null;
    const takesMatcher = target === 'claude' ? !CLAUDE_NO_MATCHER.includes(e.event) : CODEX_MATCHER_EVENTS.includes(e.event);
    if (e.matcher && takesMatcher) {
      if (target === 'codex' && TOOL_EVENTS.includes(e.event) && !e.extra.matcherRegex) {
        const tm = translateMatcher(e.matcher, CANON_TO_CODEX_TOOL, { keepUnknown: false });
        if (tm.unknown.length) dropped.push({ file, field: 'matcher', value: tm.unknown.join('|'), reason: 'Codex hooks see Bash, apply_patch (alias Edit/Write) and Agent only' });
        if (!tm.matcher) { dropped.push({ file, field: `hooks.${e.event}`, reason: 'no matcher tool name exists in Codex; entry skipped' }); continue; }
        matcher = tm.matcher;
      } else matcher = e.matcher;
    } else if (e.matcher && !takesMatcher) notes.add(`${e.event} ignores matchers in ${target}; the matcher was omitted.`);
    const groups = (hooks[e.event] ||= []);
    let g = groups.find((x) => (x.matcher ?? null) === matcher);
    if (!g) { g = matcher ? { matcher, hooks: [] } : { hooks: [] }; groups.push(g); }
    g.hooks.push(h);
  }
  if (crossHost) {
    manual.add(target === 'codex'
      ? 'Hook handlers must print Codex\'s output shape (hookSpecificOutput / decision); Codex rejects unknown output fields.'
      : 'Hook handlers must print Claude Code\'s output shape (hookSpecificOutput / decision), not Copilot\'s top-level fields.');
  }
  return { doc: { hooks }, dropped, manual: [...manual], notes: [...notes] };
}

function mergeHooksJson(existingText, doc) {
  const cur = existingText.trim() ? JSON.parse(stripBom(existingText)) : {};
  if (!cur || typeof cur !== 'object' || Array.isArray(cur)) throw new Error('existing file is not a JSON object');
  if (doc.version != null && cur.version == null) cur.version = doc.version;
  cur.hooks = cur.hooks && typeof cur.hooks === 'object' ? cur.hooks : {};
  for (const [ev, list] of Object.entries(doc.hooks)) {
    const have = (cur.hooks[ev] ||= []);
    const seen = new Set(have.map((x) => JSON.stringify(x)));
    for (const item of list) if (!seen.has(JSON.stringify(item))) have.push(item);
  }
  return JSON.stringify(cur, null, 2) + '\n';
}

