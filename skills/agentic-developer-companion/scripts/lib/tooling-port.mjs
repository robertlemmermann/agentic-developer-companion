const markerLine = (src) => `<!-- ${PORT_MARKER} ${src}; edit the source and re-run tooling port -->`;
const stripMarker = (text) => String(text).replace(/^<!-- generated by agentic-developer-companion port from [^\n]*-->\r?\n/, '');

function codeRanges(text) {
  const ranges = [];
  const re = /^(```|~~~)[^\n]*\n[\s\S]*?^\1[^\n]*$/gm;
  let m;
  while ((m = re.exec(text))) ranges.push([m.index, m.index + m[0].length]);
  return ranges;
}

/** `@path` imports (Claude Code, Copilot CLI) outside code blocks and spans. */
export function findImports(text) {
  const ranges = codeRanges(text);
  const out = [];
  const re = /(^|[\s(])@((?:\.{1,2}\/|[A-Za-z0-9_])[A-Za-z0-9_./-]*\.[A-Za-z0-9]+)(?=[\s),.;:]|$)/gm;
  let m;
  while ((m = re.exec(text))) {
    const at = m.index + m[1].length;
    if (ranges.some(([a, b]) => at >= a && at < b)) continue;
    const lineStart = text.lastIndexOf('\n', at) + 1;
    const before = text.slice(lineStart, at);
    if ((before.match(/`/g) || []).length % 2 === 1) continue;
    out.push({ ref: m[2], index: at, length: m[2].length + 1 });
  }
  return out;
}

/** Inline `@imports` recursively (depth 4, cycles skipped). Returns `{ text, missing[], files[] }`. */
export function inlineImports(text, absFile, { depth = 0, seen = new Set() } = {}) {
  const missing = [];
  const files = [];
  seen.add(path.resolve(absFile));
  const imports = findImports(text);
  let out = '';
  let last = 0;
  for (const imp of imports) {
    const target = path.resolve(path.dirname(absFile), imp.ref);
    out += text.slice(last, imp.index);
    last = imp.index + imp.length;
    const content = readText(target);
    if (content == null) { missing.push(imp.ref); out += `@${imp.ref}`; continue; }
    if (seen.has(target) || depth >= 4) { out += `@${imp.ref}`; continue; }
    files.push(target);
    const inner = inlineImports(stripMarker(content), target, { depth: depth + 1, seen });
    missing.push(...inner.missing);
    files.push(...inner.files);
    out += inner.text.replace(/\n+$/, '');
  }
  out += text.slice(last);
  return { text: out, missing, files };
}

function sectionMerge(id, block) {
  const begin = `<!-- adc:port begin ${id} -->`;
  const end = `<!-- adc:port end ${id} -->`;
  const full = `${begin}\n${block.replace(/\n+$/, '')}\n${end}\n`;
  return (existing) => {
    const cur = existing || '';
    const a = cur.indexOf(begin);
    const b = cur.indexOf(end);
    if (a >= 0 && b > a) return cur.slice(0, a) + full + cur.slice(b + end.length).replace(/^\r?\n/, '');
    return cur + (cur && !cur.endsWith('\n') ? '\n' : '') + (cur.trim() ? '\n' : '') + full;
  };
}

/** Text without the port-managed section for `id` (so a file's own imports can be inspected). */
function stripPortSections(text, id) {
  const begin = `<!-- adc:port begin ${id} -->`;
  const end = `<!-- adc:port end ${id} -->`;
  const cur = String(text || '');
  const a = cur.indexOf(begin);
  const b = cur.indexOf(end);
  return a >= 0 && b > a ? cur.slice(0, a) + cur.slice(b + end.length) : cur;
}

function convertInstructions(src, cls, targets) {
  const outputs = [];
  const dropped = [];
  const manual = [];
  const notes = [];
  const raw = stripMarker(src.text);
  const inlined = inlineImports(raw, src.abs);
  for (const ref of inlined.missing) manual.push(`Import @${ref} in ${src.rel} does not resolve; fix it before porting.`);
  const base = path.posix.basename(src.rel);
  const importsAgents = findImports(raw).some((i) => path.posix.basename(i.ref) === 'AGENTS.md');
  for (const host of targets) {
    if (host === 'codex') {
      if (base === 'AGENTS.md' || base === 'AGENTS.override.md') { notes.push(`codex: reads ${src.rel} natively`); continue; }
      if (base === 'CLAUDE.md' && importsAgents) {
        notes.push('codex: AGENTS.md is already the shared source; the Claude-only notes in CLAUDE.md are not ported');
        continue;
      }
      const content = `${markerLine(src.rel)}\n${inlined.text.replace(/^\n+/, '')}`;
      if (inlined.files.length) manual.push('Codex has no @import: imported files were inlined into AGENTS.md; re-run tooling port after editing them.');
      if (Buffer.byteLength(content) > 32768) manual.push(`AGENTS.md would be ${Buffer.byteLength(content)} bytes; Codex loads at most 32 KiB of AGENTS.md content in total.`);
      outputs.push({ path: 'AGENTS.md', content, host, kind: 'instructions' });
      if (base === 'CLAUDE.local.md') manual.push('CLAUDE.local.md is personal; consider keeping it out of the shared AGENTS.md.');
      else manual.push(`Copilot reads AGENTS.md as well as ${base}, so these rules now load twice in Copilot: prefer AGENTS.md as the single source (move the shared rules there, keep ${base} for host-only notes, and give Claude Code an @AGENTS.md import).`);
    } else if (host === 'claude') {
      if (base === 'CLAUDE.md' || base === 'CLAUDE.local.md') { notes.push(`claude: reads ${src.rel} natively`); continue; }
      const importLine = `@${src.rel}`;
      const merge = sectionMerge(src.rel, `${importLine}\n`);
      // A CLAUDE.md that already imports the source (hand-written or ported) stays as it is.
      const importMerge = (cur) => (findImports(stripPortSections(cur, src.rel)).some((i) => toPosix(i.ref).replace(/^\.\//, '') === src.rel) ? cur : merge(cur));
      outputs.push({ path: 'CLAUDE.md', content: merge(`${markerLine(src.rel)}\n`), merge: importMerge, host, kind: 'instructions' });
      if (base === 'AGENTS.md') notes.push('claude: Claude Code reads AGENTS.md only when no CLAUDE.md exists; the @AGENTS.md import keeps one source for both');
      else manual.push(`Copilot CLI also reads CLAUDE.md: check \`copilot instruction list --json\` that ${src.rel} is not loaded twice.`);
    } else if (host === 'copilot') {
      if (base === 'AGENTS.md') {
        notes.push('copilot: Copilot CLI, the cloud agent and VS Code read AGENTS.md natively');
        manual.push('Copilot code review documents only .github/copilot-instructions.md and path-specific files; add review-relevant rules there if code review must see them.');
        continue;
      }
      if (src.rel === '.github/copilot-instructions.md') { notes.push('copilot: native'); continue; }
      if (base === 'AGENTS.override.md') manual.push('AGENTS.override.md is a Codex-only local override; porting it to Copilot makes it shared.');
      outputs.push({ path: '.github/copilot-instructions.md', content: inlined.text, host, kind: 'instructions' });
      if (base === 'CLAUDE.md' || base === 'GEMINI.md') manual.push(`Copilot CLI and the cloud agent also read ${base} directly: keep one of the two files minimal to avoid loading the rules twice.`);
    }
  }
  return { outputs, dropped, manual, notes };
}

/** Static directory prefix of a glob (`src/api/**\/*.ts` → `src/api`). */
function globDirPrefix(glob) {
  const segs = toPosix(glob).replace(/^\.\//, '').split('/');
  const out = [];
  for (let k = 0; k < segs.length - 1; k++) {
    if (/[*?[\]{}]/.test(segs[k])) break;
    out.push(segs[k]);
  }
  return out.join('/');
}

function parseScoped(src, cls) {
  const fm = readFrontmatter(src.text);
  const base = path.posix.basename(src.rel);
  let topic;
  let globs = [];
  if (cls.host === 'copilot' && /\.instructions\.md$/.test(base)) {
    topic = base.replace(/\.instructions\.md$/, '');
    globs = asList(fm.data.applyTo);
  } else if (cls.host === 'claude' && /(^|\/)\.claude\/rules\//.test(src.rel)) {
    topic = base.replace(/\.md$/, '');
    globs = asList(fm.data.paths);
  } else {
    const dir = cls.scopeDir || path.posix.dirname(src.rel);
    topic = toSkillName(dir);
    globs = [`${dir}/**`];
  }
  return { topic, globs, description: asText(fm.data.description), name: asText(fm.data.name), excludeAgent: asText(fm.data.excludeAgent),
    body: fm.hasFrontmatter ? fm.body.replace(/^\r?\n/, '') : stripMarker(fm.body), data: fm.data, errors: fm.errors };
}

function convertScoped(src, cls, targets) {
  const outputs = [];
  const dropped = [];
  const manual = [];
  const notes = [];
  const s = parseScoped(src, cls);
  const always = !s.globs.length || s.globs.some((g) => g === '**' || g === '**/*');
  for (const host of targets) {
    if (host === cls.host) { notes.push(`${host}: native`); continue; }
    if (host === 'copilot') {
      const data = { applyTo: always ? '**' : s.globs.join(',') };
      if (s.description) data.description = s.description;
      outputs.push({ path: `.github/instructions/${s.topic}.instructions.md`, content: stringifyFrontmatter(data) + '\n' + s.body.replace(/^\n+/, ''), host, kind: 'scoped' });
    } else if (host === 'claude') {
      const data = {};
      if (!always) data.paths = s.globs;
      if (s.description) data.description = s.description;
      if (s.excludeAgent) dropped.push({ file: src.rel, field: 'excludeAgent', value: s.excludeAgent, reason: 'Claude Code rules have no excludeAgent' });
      const fmText = Object.keys(data).length ? stringifyFrontmatter(data) + '\n' : '';
      outputs.push({ path: `.claude/rules/${s.topic}.md`, content: fmText + s.body.replace(/^\n+/, ''), host, kind: 'scoped' });
      if (always) notes.push('claude: a rule without paths loads in every session');
    } else if (host === 'codex') {
      if (s.excludeAgent) dropped.push({ file: src.rel, field: 'excludeAgent', value: s.excludeAgent, reason: 'Codex has no excludeAgent' });
      const byDir = new Map();
      for (const g of always ? ['**'] : s.globs) {
        const dir = globDirPrefix(g);
        if (!byDir.has(dir)) byDir.set(dir, []);
        byDir.get(dir).push(g);
        const exact = g === `${dir}/**` || (dir === '' && (g === '**' || g === '**/*'));
        if (!exact) dropped.push({ file: src.rel, field: 'applyTo', value: g, reason: `Codex scopes AGENTS.md by directory only; the rules apply to every file under ${dir || 'the repository root'}/` });
      }
      for (const [dir, gl] of byDir) {
        const title = s.description || s.name || s.topic;
        const block = `## ${title}\n\nApplies to: ${gl.map((g) => `\`${g}\``).join(', ')}\n\n${s.body.replace(/^\n+/, '').replace(/\n+$/, '')}\n`;
        const target = dir ? `${dir}/AGENTS.md` : 'AGENTS.md';
        outputs.push({ path: target, content: sectionMerge(src.rel, block)(''), merge: sectionMerge(src.rel, block), host, kind: 'scoped' });
      }
    }
  }
  return { outputs, dropped, manual, notes };
}

const COPILOT_AGENT_FIELDS = ['name', 'description', 'target', 'tools', 'model', 'disable-model-invocation', 'user-invocable', 'infer', 'mcp-servers',
  'metadata', 'argument-hint', 'handoffs', 'include-custom-instructions', 'models', 'modelPolicy', 'reasoningEffort', 'skills', 'hooks'];
const CLAUDE_AGENT_FIELDS = ['name', 'description', 'tools', 'disallowedTools', 'model', 'permissionMode', 'maxTurns', 'autoCompactWindow', 'skills',
  'mcpServers', 'hooks', 'memory', 'background', 'omitClaudeMd', 'effort', 'isolation', 'color', 'initialPrompt', 'experimental',
  'user-invocable', 'disable-model-invocation'];

/** Agent file → IR `{ name, description, tools (Claude names | null = all), model, ... , body, extra }`. */
export function parseAgent(text, host, rel) {
  const fm = readFrontmatter(text);
  const d = fm.data;
  const stem = path.posix.basename(rel).replace(/\.agent\.md$|\.chatmode\.md$|\.md$/, '');
  const ir = { name: asText(d.name) || stem, description: asText(d.description), tools: null, toolsUnknown: [], model: asText(d.model),
    userInvocable: asBool(d['user-invocable']), disableModelInvocation: asBool(d['disable-model-invocation']), skills: d.skills != null ? asList(d.skills) : null,
    includeInstructions: null, effort: null, body: fm.body.replace(/^\r?\n/, ''), extra: {}, source: host, errors: fm.errors };
  const known = host === 'copilot' ? COPILOT_AGENT_FIELDS : CLAUDE_AGENT_FIELDS;
  if (host === 'copilot') {
    if (d.tools != null) { const t = toolsCopilotToCanonical(asList(d.tools)); ir.tools = t.tools; ir.toolsUnknown = t.unknown; }
    // Copilot subagents get no repository instructions unless this is true (default false).
    ir.includeInstructions = asBool(d['include-custom-instructions']) === true;
    if (d.reasoningEffort != null) ir.effort = asText(d.reasoningEffort);
    if (d.infer != null && ir.disableModelInvocation == null) ir.disableModelInvocation = asBool(d.infer) === false ? true : null;
    for (const k of ['target', 'mcp-servers', 'metadata', 'argument-hint', 'handoffs', 'models', 'modelPolicy', 'hooks', 'infer']) if (d[k] != null) ir.extra[k] = d[k];
  } else {
    if (d.tools != null) { const list = asList(d.tools); ir.tools = list.includes('*') ? null : [...new Set(list.map((t) => (t === 'Task' ? 'Agent' : t)))]; }
    const omit = asBool(d.omitClaudeMd);
    ir.includeInstructions = omit === true ? false : true;
    if (d.effort != null) ir.effort = asText(d.effort);
    for (const k of ['disallowedTools', 'permissionMode', 'maxTurns', 'autoCompactWindow', 'mcpServers', 'hooks', 'memory', 'background', 'isolation', 'color', 'initialPrompt', 'experimental']) {
      if (d[k] != null) ir.extra[k] = d[k];
    }
  }
  for (const k of Object.keys(d)) if (!known.includes(k)) ir.extra[k] = d[k];
  return ir;
}

/** Render an agent IR for copilot or claude. Returns `{ path, content, dropped[], manual[] }`. */
export function renderAgent(ir, host, { file = ir.name, pluginScoped = false } = {}) {
  const dropped = [];
  const manual = [];
  const drop = (field, reason) => dropped.push({ file, field, value: typeof ir.extra[field] === 'string' ? ir.extra[field] : undefined, reason });
  const data = {};
  if (host === 'copilot') {
    data.name = ir.name;
    data.description = ir.description ?? '';
    if (ir.tools) {
      const t = toolsCanonicalToCopilot(ir.tools);
      data.tools = t.tools;
      if (t.unmapped.length) dropped.push({ file, field: 'tools', value: t.unmapped.join(', '), reason: 'no Copilot tool alias' });
    }
    if (ir.model) { data.model = ir.model; if (ir.source !== 'copilot') manual.push(`Check that model "${ir.model}" is a valid Copilot model name for ${ir.name}.`); }
    if (ir.userInvocable != null) data['user-invocable'] = ir.userInvocable;
    if (ir.disableModelInvocation != null) data['disable-model-invocation'] = ir.disableModelInvocation;
    if (ir.includeInstructions === true) data['include-custom-instructions'] = true;
    if (ir.skills) data.skills = ir.skills;
    if (ir.effort && /^(low|medium|high)$/.test(ir.effort)) data.reasoningEffort = ir.effort;
    else if (ir.effort) dropped.push({ file, field: 'effort', value: ir.effort, reason: 'no matching Copilot reasoningEffort value' });
    for (const k of Object.keys(ir.extra)) {
      if (ir.source === 'copilot') data[k] = ir.extra[k];
      else drop(k, k === 'disallowedTools' ? 'Copilot agents have no deny list; narrow tools instead' : `Copilot agents have no "${k}"`);
    }
    if (ir.body.length > 30000) manual.push(`${ir.name}: the body has ${ir.body.length} characters; Copilot agents allow at most 30,000.`);
    const content = stringifyFrontmatter(data, { flowKeys: ['tools', 'skills'] }) + '\n' + ir.body.replace(/^\n+/, '');
    return { path: `.github/agents/${agentFileName(ir.name)}.agent.md`, content, dropped, manual };
  }
  data.name = String(ir.name).replace(/:/g, '-');
  if (data.name !== ir.name) manual.push(`Claude Code agent names cannot contain ":"; renamed ${ir.name} to ${data.name}.`);
  data.description = ir.description ?? '';
  if (!ir.description) manual.push(`${ir.name}: Claude Code requires a description for subagents.`);
  if (ir.tools) data.tools = ir.tools.join(', ');
  if (ir.model) { data.model = ir.model; if (ir.source !== 'claude') manual.push(`Check that model "${ir.model}" is valid for Claude Code (sonnet, opus, haiku, inherit or a full model id).`); }
  if (ir.skills) data.skills = ir.skills;
  if (ir.effort) data.effort = ir.effort;
  if (ir.includeInstructions === false) {
    data.omitClaudeMd = true;
    if (ir.source === 'copilot') manual.push(`${ir.name}: Copilot subagents get no repository instructions without include-custom-instructions: true, so the Claude Code agent sets omitClaudeMd: true; remove it to give the agent CLAUDE.md.`);
  }
  if (ir.userInvocable != null) data['user-invocable'] = ir.userInvocable;
  if (ir.disableModelInvocation != null) data['disable-model-invocation'] = ir.disableModelInvocation;
  if (ir.toolsUnknown.length) manual.push(`${ir.name}: tool names ${ir.toolsUnknown.join(', ')} are not Copilot aliases; check them in Claude Code.`);
  for (const k of Object.keys(ir.extra)) {
    if (ir.source === 'claude') {
      if (pluginScoped && ['hooks', 'mcpServers', 'permissionMode'].includes(k)) { drop(k, 'plugin subagents ignore hooks, mcpServers and permissionMode'); continue; }
      data[k] = ir.extra[k];
    } else drop(k, `Claude Code subagents have no "${k}"`);
  }
  if (ir.source !== 'claude' && (ir.userInvocable != null || ir.disableModelInvocation != null)) {
    manual.push(`${ir.name}: user-invocable / disable-model-invocation are kept for round trips; Claude Code subagents do not document them.`);
  }
  const content = stringifyFrontmatter(data, { flowKeys: ['skills'] }) + '\n' + ir.body.replace(/^\n+/, '');
  return { path: `.claude/agents/${data.name}.md`, content, dropped, manual };
}

function firstSentence(text) {
  const s = String(text || '').replace(/\s+/g, ' ').trim();
  const m = /^(.{10,}?[.!?])(\s|$)/.exec(s);
  return (m ? m[1] : s).slice(0, 200);
}

/** 25-64 characters for Codex's metadata.short-description, or null. */
export function shortDescription(text) {
  const s = firstSentence(text).replace(/[.!?]$/, '');
  if (s.length >= 25 && s.length <= 64) return s;
  if (s.length > 64) {
    const cut = s.slice(0, 64);
    const words = cut.slice(0, cut.lastIndexOf(' ') > 25 ? cut.lastIndexOf(' ') : 64);
    return words.length >= 25 ? words : null;
  }
  return null;
}

/** `agents/openai.yaml` for a Codex skill (D9: generated only for the user's own skills). */
export function renderOpenAiYaml({ name, description, implicit = true, defaultPrompt = null }) {
  const data = { interface: { display_name: name } };
  const sd = shortDescription(description);
  if (sd) data.interface.short_description = sd;
  data.interface.default_prompt = defaultPrompt || `Use $${name}: ${firstSentence(description) || 'help with this task.'}`;
  data.policy = { allow_implicit_invocation: Boolean(implicit) };
  return stringifyYaml(data).join('\n') + '\n';
}

function skillFrontmatter({ name, description, extra = {}, host }) {
  const data = { name, description: description || `Runs the ${name} workflow.` };
  for (const [k, v] of Object.entries(extra)) if (v != null) data[k] = v;
  if (host === 'codex') {
    const sd = shortDescription(description);
    if (sd) data.metadata = { ...(data.metadata || {}), 'short-description': sd };
  }
  return stringifyFrontmatter(data, { flowKeys: [] });
}

const PROMPT_VARS = /\$\{(input:[^}]+|selection|selectedText|file|fileBasename|fileDirname|fileBasenameNoExtension|workspaceFolder|workspaceFolderBasename)\}|#(file|tool):[^\s,;)]*[^\s,;).]/g;
const CLAUDE_PLACEHOLDERS = /\$ARGUMENTS(\[\d+\])?|\$\d\b|\$\{CLAUDE_[A-Z_]+\}|(^|\s)!`[^`]+`/m;

function convertPromptLike(src, cls, targets) {
  const outputs = [];
  const dropped = [];
  const manual = [];
  const notes = [];
  const fm = readFrontmatter(src.text);
  const d = fm.data;
  const base = path.posix.basename(src.rel);
  let label;
  if (cls.kind === 'command') {
    const m = /\.claude\/commands\/(.+)\.md$/.exec(src.rel);
    label = (m ? m[1] : base.replace(/\.md$/, '')).split('/').join('-');
  } else label = asText(d.name) || base.replace(/\.prompt\.md$/, '');
  const name = toSkillName(label);
  if (name !== label) notes.push(`skill name "${name}" derived from "${label}"`);
  const body = fm.body.replace(/^\r?\n/, '');
  let description = asText(d.description);
  if (!description) {
    description = firstSentence(body.replace(/^#.*$/m, '')) || `Runs the ${name} prompt.`;
    manual.push(`${src.rel} has no description; "${description}" was derived from the body. Rewrite it as what + when + boundary.`);
  }
  const vars = [...new Set([...`${description}\n${body}`.matchAll(PROMPT_VARS)].map((m) => m[0]))];
  for (const host of targets) {
    const dir = `${SKILL_DIRS[host]}/${name}`;
    const extra = {};
    if (cls.kind === 'prompt') {
      for (const k of ['agent', 'model', 'tools']) if (d[k] != null) dropped.push({ file: src.rel, field: k, value: asText(d[k]), reason: 'prompt-file field with no skill equivalent (VS Code drops it too)' });
      if (host !== 'codex') {
        if (d['argument-hint'] != null) extra['argument-hint'] = asText(d['argument-hint']);
        extra['disable-model-invocation'] = true;
      } else if (d['argument-hint'] != null) dropped.push({ file: src.rel, field: 'argument-hint', reason: 'Codex ignores argument-hint' });
      if (vars.length) manual.push(`Rewrite prompt-file variables ${vars.join(', ')} in ${dir}/SKILL.md: skills receive the words after the skill name instead.`);
    } else {
      if (d['allowed-tools'] != null) extra['allowed-tools'] = asText(d['allowed-tools']).replace(/,\s*/g, ' ');
      if (host !== 'codex') {
        if (d['argument-hint'] != null) extra['argument-hint'] = asText(d['argument-hint']);
        if (d['disable-model-invocation'] != null) extra['disable-model-invocation'] = asBool(d['disable-model-invocation']);
      }
      if (d.model != null) {
        if (host === 'claude') extra.model = asText(d.model);
        else dropped.push({ file: src.rel, field: 'model', value: asText(d.model), reason: `${host} skills have no model field` });
      }
      if (host !== 'claude' && CLAUDE_PLACEHOLDERS.test(body)) manual.push(`${dir}/SKILL.md uses Claude-only placeholders or !\`cmd\` blocks; ${host} does not expand them.`);
      if (host === 'claude') manual.push(`Delete ${src.rel} once the skill works: a skill with the same name takes precedence, and two copies drift.`);
    }
    for (const k of Object.keys(d)) {
      if (!['name', 'description', 'argument-hint', 'agent', 'model', 'tools', 'allowed-tools', 'disable-model-invocation'].includes(k)) {
        dropped.push({ file: src.rel, field: k, reason: 'not a skill field' });
      }
    }
    const content = skillFrontmatter({ name, description, extra, host }) + '\n' + body;
    outputs.push({ path: `${dir}/SKILL.md`, content, host, kind: 'skill' });
    if (host === 'codex') {
      const implicit = cls.kind === 'prompt' ? false : asBool(d['disable-model-invocation']) !== true;
      outputs.push({ path: `${dir}/agents/openai.yaml`, content: renderOpenAiYaml({ name, description, implicit }), host, kind: 'skill' });
    }
  }
  return { outputs, dropped, manual, notes };
}

function convertChatmode(src, cls) {
  const ir = parseAgent(src.text, 'copilot', src.rel);
  ir.extra = Object.fromEntries(Object.entries(ir.extra).filter(([k]) => k !== 'tools'));
  const fm = readFrontmatter(src.text);
  const rawTools = fm.data.tools != null ? asList(fm.data.tools) : null;
  const data = { name: ir.name, description: ir.description || `${ir.name} agent` };
  if (rawTools) data.tools = rawTools;
  if (ir.model) data.model = ir.model;
  const manual = [];
  if (!ir.description) manual.push(`${src.rel} has no description; Copilot agents require one.`);
  if (rawTools) manual.push(`Check the tools of ${ir.name}: chat-mode tool names (${rawTools.join(', ')}) are VS Code tool sets; agents use the aliases read, edit, search, execute, agent, web and todo. Unknown names are ignored.`);
  const dropped = Object.keys(fm.data).filter((k) => !['name', 'description', 'tools', 'model'].includes(k)).map((k) => ({ file: src.rel, field: k, reason: 'not a custom-agent field' }));
  const content = stringifyFrontmatter(data, { flowKeys: ['tools'] }) + '\n' + ir.body.replace(/^\n+/, '');
  return { outputs: [{ path: `.github/agents/${agentFileName(ir.name)}.agent.md`, content, host: 'copilot', kind: 'agent' }], dropped, manual, notes: [] };
}

