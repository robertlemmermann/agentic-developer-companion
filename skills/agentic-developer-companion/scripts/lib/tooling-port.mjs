/** Agent Skills name rules: 1-64, lowercase letters, digits, single hyphens. */
export function skillNameProblems(name) {
  const n = String(name ?? '');
  const problems = [];
  if (!n || n.length > 64) problems.push('must be 1-64 characters');
  if (!/^[a-z0-9-]*$/.test(n)) problems.push('only lowercase letters, digits and hyphens');
  if (/^-|-$/.test(n)) problems.push('must not start or end with a hyphen');
  if (n.includes('--')) problems.push('must not contain consecutive hyphens');
  if (/(^|-)(claude|anthropic)(-|$)/.test(n)) problems.push('must not contain the reserved words claude or anthropic');
  return problems;
}

/** Best-effort conversion of any label into a valid skill name. */
export function toSkillName(label) {
  const n = String(label ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-+/g, '-').replace(/^-|-$/g, '').slice(0, 64).replace(/-$/, '');
  return n || 'skill';
}

