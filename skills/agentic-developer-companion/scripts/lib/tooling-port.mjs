/**
 * Classify a tooling file by its repository-relative path:
 * `{ kind, host, hosts[], name? }` or null. `hosts` are the hosts that load it from there.
 */
export function classifyArtifact(relPath) {
  const p = toPosix(relPath).replace(/^\.\//, '');
  const base = path.posix.basename(p);
  const dir = path.posix.dirname(p);
  let m;
  if (/(^|\/)\.github\/copilot-instructions\.md$/.test(p)) return { kind: 'instructions', host: 'copilot', hosts: ['copilot'] };
  if (/(^|\/)\.github\/instructions\/.+\.instructions\.md$/.test(p)) return { kind: 'scoped', host: 'copilot', hosts: ['copilot'] };
  if (/(^|\/)\.claude\/rules\/.+\.md$/.test(p)) return { kind: 'scoped', host: 'claude', hosts: ['claude', 'copilot'] };
  if (/(^|\/)\.github\/agents\/.+\.md$/.test(p)) return { kind: 'agent', host: 'copilot', hosts: ['copilot'] };
  if (/(^|\/)\.claude\/agents\/.+\.md$/.test(p)) return { kind: 'agent', host: 'claude', hosts: ['claude', 'copilot'] };
  if (/(^|\/)\.codex\/agents\/.+\.toml$/.test(p)) return { kind: 'agent-toml', host: 'codex', hosts: ['codex'] };
  if (/(^|\/)\.github\/prompts\/.+\.prompt\.md$/.test(p)) return { kind: 'prompt', host: 'copilot', hosts: ['copilot'] };
  if (/(^|\/)\.github\/chatmodes\/.+\.chatmode\.md$/.test(p)) return { kind: 'chatmode', host: 'copilot', hosts: ['copilot'] };
  if (/(^|\/)\.claude\/commands\/.+\.md$/.test(p)) return { kind: 'command', host: 'claude', hosts: ['claude', 'copilot'] };
  if ((m = /^(?:(.*)\/)?((?:\.github|\.agents|\.claude|\.codex)\/skills)\/([^/]+)\/(.+)$/.exec(p)) || (m = /^(?:(.*)\/)?(skills)\/([^/]+)\/(.+)$/.exec(p))) {
    const loc = skillDirHosts(m[2]);
    if (m[4] === 'SKILL.md') return { kind: 'skill', ...loc, name: m[3], dir: [m[1], m[2], m[3]].filter(Boolean).join('/') };
    if (/\.md$/i.test(m[4])) return { kind: 'skill-file', ...loc, name: m[3], dir: [m[1], m[2], m[3]].filter(Boolean).join('/') };
    return null;
  }
  if (/(^|\/)\.github\/hooks\/[^/]+\.json$/.test(p) || /(^|\/)\.copilot\/hooks\/[^/]+\.json$/.test(p)) return { kind: 'hooks', host: 'copilot', hosts: ['copilot'] };
  if (/(^|\/)\.github\/copilot\/settings(\.local)?\.json$/.test(p) || /(^|\/)\.copilot\/settings\.json$/.test(p)) return { kind: 'hooks', host: 'copilot', hosts: ['copilot'], settings: true };
  if (/(^|\/)\.claude\/settings(\.local)?\.json$/.test(p)) return { kind: 'hooks', host: 'claude', hosts: ['claude', 'copilot'], settings: true };
  if (/(^|\/)\.codex\/hooks\.json$/.test(p)) return { kind: 'hooks', host: 'codex', hosts: ['codex'] };
  if (/(^|\/)\.vscode\/mcp\.json$/.test(p)) return { kind: 'mcp', host: 'vscode', hosts: ['copilot'], dialect: 'vscode' };
  if (/(^|\/)\.github\/mcp\.json$/.test(p) || base === 'mcp-config.json') return { kind: 'mcp', host: 'copilot', hosts: ['copilot'], dialect: 'mcpServers' };
  if (base === '.mcp.json') return { kind: 'mcp', host: 'claude', hosts: ['claude', 'copilot'], dialect: 'mcpServers' };
  if (/(^|\/)\.codex\/config\.toml$/.test(p) || p === 'config.toml') return { kind: 'mcp', host: 'codex', hosts: ['codex'], dialect: 'toml' };
  if (base === 'mcp.json') return { kind: 'mcp', host: 'portable', hosts: [...HOSTS], dialect: 'agent-plugins' };
  if (/(^|\/)\.claude-plugin\/plugin\.json$/.test(p)) return { kind: 'plugin', host: 'claude', hosts: ['claude', 'copilot'] };
  if (/(^|\/)\.codex-plugin\/plugin\.json$/.test(p)) return { kind: 'plugin', host: 'codex', hosts: ['codex'] };
  if (base === 'plugin.json') return { kind: 'plugin', host: 'portable', hosts: [...HOSTS] };
  if (base === 'marketplace.json') return { kind: 'marketplace', host: 'portable', hosts: [...HOSTS] };
  if (base === 'AGENTS.override.md') return { kind: dir === '.' ? 'instructions' : 'scoped', host: 'codex', hosts: ['codex'] };
  if (base === 'AGENTS.md') {
    return dir === '.' ? { kind: 'instructions', host: 'portable', hosts: ['copilot', 'codex', 'claude'] }
      : { kind: 'scoped', host: 'codex', hosts: ['copilot', 'codex', 'claude'], scopeDir: dir };
  }
  if (base === 'CLAUDE.md' || base === 'CLAUDE.local.md') {
    const top = dir === '.' || dir === '.claude';
    return { kind: top ? 'instructions' : 'scoped', host: 'claude', hosts: base === 'CLAUDE.local.md' ? ['claude'] : ['claude', 'copilot'], ...(top ? {} : { scopeDir: dir }) };
  }
  if (base === 'GEMINI.md') return { kind: 'instructions', host: 'copilot', hosts: ['copilot'] };
  return null;
}

