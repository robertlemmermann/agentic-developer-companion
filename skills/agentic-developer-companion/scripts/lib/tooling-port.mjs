let fmLib;
/** Load frontmatter.mjs once (dynamic: it is another work package); null when absent. */
export async function loadFrontmatterLib() {
  if (fmLib !== undefined) return fmLib;
  try {
    const mod = await import('./frontmatter.mjs');
    fmLib = typeof mod.parseFrontmatter === 'function' ? mod : null;
  } catch {
    fmLib = null;
  }
  return fmLib;
}

/** Split frontmatter (`---` on line 1) from the body; the body is returned byte-exact. */
export function splitFrontmatter(text) {
  const src = stripBom(String(text ?? ''));
  const lines = src.split('\n');
  if (lines[0].replace(/\r$/, '') !== '---') return { hasFrontmatter: false, yaml: '', body: src, bodyStartLine: 1 };
  for (let i = 1; i < lines.length; i++) {
    const l = lines[i].replace(/\r$/, '');
    if (l === '---' || l === '...') {
      return {
        hasFrontmatter: true,
        yaml: lines.slice(1, i).map((x) => x.replace(/\r$/, '')).join('\n'),
        body: lines.slice(i + 1).join('\n'),
        bodyStartLine: i + 2,
      };
    }
  }
  return { hasFrontmatter: false, unterminated: true, yaml: '', body: src, bodyStartLine: 1 };
}

/** `{ data, body, hasFrontmatter, errors[], bodyStartLine }` for a Markdown file with frontmatter. */
export function readFrontmatter(text) {
  const split = splitFrontmatter(text);
  if (!split.hasFrontmatter) {
    return { data: {}, body: split.body, hasFrontmatter: false, bodyStartLine: 1,
      errors: split.unterminated ? ['frontmatter opened with --- but never closed'] : [] };
  }
  let data = null;
  let errors = [];
  if (fmLib) {
    try {
      const r = fmLib.parseFrontmatter(stripBom(String(text)));
      if (r && r.data && typeof r.data === 'object' && !Array.isArray(r.data)) {
        data = r.data;
        errors = Array.isArray(r.errors) ? r.errors.map((e) => (typeof e === 'string' ? e : e.message || String(e))) : [];
      }
    } catch {
      data = null;
    }
  }
  if (!data) {
    const local = parseYamlLocal(split.yaml);
    data = local.value && typeof local.value === 'object' && !Array.isArray(local.value) ? local.value : {};
    errors = local.errors;
  }
  return { data, body: split.body, hasFrontmatter: true, errors, bodyStartLine: split.bodyStartLine };
}

const KEY_RE = /^(?:"((?:[^"\\]|\\.)*)"|'((?:[^']|'')*)'|([^\s#'"[\]{},&*!|>%@`-][^#]*?|-[^\s#][^#]*?))\s*:(?:\s+(.*)|)$/;

function splitKey(t) {
  const m = KEY_RE.exec(t);
  if (!m) return null;
  let key;
  if (m[1] !== undefined) {
    try { key = JSON.parse(`"${m[1]}"`); } catch { key = m[1]; }
  } else if (m[2] !== undefined) key = m[2].replace(/''/g, "'");
  else key = m[3].trim();
  return { key, rest: (m[4] || '').trim() };
}

function stripComment(s) {
  let q = null;
  for (let i = 0; i < s.length; i++) {
    const c = s[i];
    if (q) { if (c === q && (q === "'" || s[i - 1] !== '\\')) q = null; continue; }
    if ((c === '"' || c === "'") && (i === 0 || /[\s[{,:]/.test(s[i - 1]))) { q = c; continue; }
    if (c === '#' && (i === 0 || /\s/.test(s[i - 1]))) return s.slice(0, i).trimEnd();
  }
  return s.trimEnd();
}

function resolvePlain(s) {
  const v = s.trim();
  if (/^(true|false)$/i.test(v)) return v.toLowerCase() === 'true';
  if (v === '' || v === '~' || /^null$/i.test(v)) return null;
  return v;
}

function parseDoubleQuoted(s) {
  let out = '';
  for (let i = 1; i < s.length; i++) {
    const c = s[i];
    if (c === '"') return { value: out, rest: s.slice(i + 1) };
    if (c === '\\') {
      const n = s[++i];
      const map = { n: '\n', t: '\t', r: '\r', '"': '"', '\\': '\\', '/': '/', '0': '\0', b: '\b', f: '\f', ' ': ' ', e: '\x1b' };
      if (n in map) out += map[n];
      else if (n === 'x') { out += String.fromCharCode(parseInt(s.slice(i + 1, i + 3), 16)); i += 2; }
      else if (n === 'u') { out += String.fromCharCode(parseInt(s.slice(i + 1, i + 5), 16)); i += 4; }
      else if (n === 'U') { out += String.fromCodePoint(parseInt(s.slice(i + 1, i + 9), 16)); i += 8; }
      else out += n ?? '';
      continue;
    }
    out += c;
  }
  return null;
}

function parseSingleQuoted(s) {
  let out = '';
  for (let i = 1; i < s.length; i++) {
    if (s[i] === "'") {
      if (s[i + 1] === "'") { out += "'"; i++; continue; }
      return { value: out, rest: s.slice(i + 1) };
    }
    out += s[i];
  }
  return null;
}

/** Flow collections (`[a, 'b']`, `{k: v}`) on one logical line. */
function parseFlow(src) {
  let i = 0;
  const ws = () => { while (i < src.length && /\s/.test(src[i])) i++; };
  const scalar = (stops) => {
    ws();
    if (src[i] === '"') { const r = parseDoubleQuoted(src.slice(i)); if (!r) throw new Error('unterminated string'); i = src.length - r.rest.length; return r.value; }
    if (src[i] === "'") { const r = parseSingleQuoted(src.slice(i)); if (!r) throw new Error('unterminated string'); i = src.length - r.rest.length; return r.value; }
    let start = i;
    while (i < src.length && !stops.includes(src[i])) i++;
    return resolvePlain(src.slice(start, i));
  };
  const node = () => {
    ws();
    if (src[i] === '[') {
      i++; const arr = [];
      for (;;) {
        ws();
        if (src[i] === ']') { i++; return arr; }
        arr.push(node());
        ws();
        if (src[i] === ',') { i++; continue; }
        if (src[i] === ']') { i++; return arr; }
        throw new Error('expected , or ]');
      }
    }
    if (src[i] === '{') {
      i++; const obj = {};
      for (;;) {
        ws();
        if (src[i] === '}') { i++; return obj; }
        const k = scalar([':', ',', '}']);
        ws();
        let v = null;
        if (src[i] === ':') { i++; v = node(); }
        obj[String(k)] = v;
        ws();
        if (src[i] === ',') { i++; continue; }
        if (src[i] === '}') { i++; return obj; }
        throw new Error('expected , or }');
      }
    }
    return scalar([',', ']', '}']);
  };
  const v = node();
  ws();
  if (i < src.length && !src.slice(i).trim().startsWith('#')) throw new Error(`unexpected "${src.slice(i, i + 10)}"`);
  return v;
}

/**
 * The YAML subset hosts use in frontmatter: block maps and lists, flow collections,
 * quoted, plain (multi-line) and block (`|`, `>`, chomping) scalars, comments.
 * Plain scalars stay strings except true/false/null. Returns `{ value, errors[] }`.
 */
export function parseYamlLocal(text) {
  const errors = [];
  const lines = String(text ?? '').split(/\r?\n/).map((raw, idx) => {
    const t = raw.trim();
    return { raw, n: idx + 1, indent: raw.length - raw.replace(/^ +/, '').length, t };
  });
  let i = 0;
  const skippable = (l) => !l.t || l.t.startsWith('#');
  const nextContent = (from) => { let j = from; while (j < lines.length && skippable(lines[j])) j++; return j; };
  const isDash = (t) => t === '-' || t.startsWith('- ');

  function blockScalar(indicator, parentIndent) {
    const style = indicator[0];
    const chomp = indicator.includes('-') ? 'strip' : indicator.includes('+') ? 'keep' : 'clip';
    const explicit = /\d/.exec(indicator);
    let blockIndent = explicit ? parentIndent + Number(explicit[0]) : null;
    const body = [];
    while (i < lines.length) {
      const l = lines[i];
      if (!l.t) { body.push(''); i++; continue; }
      if (blockIndent === null) { if (l.indent <= parentIndent) break; blockIndent = l.indent; }
      if (l.indent < blockIndent) break;
      body.push(l.raw.slice(blockIndent));
      i++;
    }
    let trailing = 0;
    while (body.length && body[body.length - 1] === '') { body.pop(); trailing++; }
    let out;
    if (style === '|') out = body.join('\n');
    else {
      out = '';
      let blank = 0;
      let prevMore = false;
      let started = false;
      for (const line of body) {
        if (line === '') { blank++; continue; }
        const more = /^\s/.test(line);
        if (!started) out = '\n'.repeat(blank) + line;
        else if (blank) out += '\n'.repeat(blank) + line;
        else if (more || prevMore) out += '\n' + line;
        else out += ' ' + line;
        started = true; blank = 0; prevMore = more;
      }
    }
    if (!body.length) return '';
    if (chomp === 'strip') return out;
    if (chomp === 'keep') return out + '\n'.repeat(trailing + 1);
    return out + '\n';
  }

  function flowValue(first, l) {
    let src = first;
    let depth = 0;
    const balance = (s) => { let d = 0; let q = null; for (let k = 0; k < s.length; k++) { const c = s[k]; if (q) { if (c === q) q = null; continue; } if (c === '"' || c === "'") q = c; else if (c === '[' || c === '{') d++; else if (c === ']' || c === '}') d--; } return d; };
    depth = balance(src);
    while (depth > 0 && i < lines.length) { src += ' ' + lines[i].t; i++; depth = balance(src); }
    try { return parseFlow(stripComment(src)); } catch (err) { errors.push(`line ${l.n}: ${err.message}`); return null; }
  }

  function quotedValue(first, l) {
    let src = first;
    for (;;) {
      const r = src.startsWith('"') ? parseDoubleQuoted(src) : parseSingleQuoted(src);
      if (r) {
        if (stripComment(r.rest).trim()) errors.push(`line ${l.n}: text after closing quote`);
        return r.value;
      }
      if (i >= lines.length) { errors.push(`line ${l.n}: unterminated quoted scalar`); return src.slice(1); }
      src += ' ' + lines[i].t;
      i++;
    }
  }

  function inlineValue(rest, l, indent) {
    if (/^[|>][+-]?[1-9]?[+-]?$/.test(rest)) return blockScalar(rest, indent);
    if (rest.startsWith('"') || rest.startsWith("'")) return quotedValue(rest, l);
    const r = stripComment(rest);
    if (r.startsWith('[') || r.startsWith('{')) return flowValue(r, l);
    if (r.startsWith('&') || r.startsWith('*') || r.startsWith('!')) {
      errors.push(`line ${l.n}: anchors, aliases and tags are not supported`);
    }
    let s = r;
    while (i < lines.length) {
      const nl = lines[i];
      if (!nl.t || nl.indent <= indent || nl.t.startsWith('#') || isDash(nl.t) || splitKey(nl.t)) break;
      s += ' ' + stripComment(nl.t);
      i++;
    }
    return resolvePlain(s);
  }

  function parseNode(indent) {
    i = nextContent(i);
    if (i >= lines.length) return null;
    const l = lines[i];
    return isDash(l.t) ? parseSeq(l.indent) : parseMap(l.indent);
  }

  function parseSeq(indent) {
    const out = [];
    for (;;) {
      i = nextContent(i);
      if (i >= lines.length) break;
      const l = lines[i];
      if (l.indent < indent || !isDash(l.t)) break;
      if (l.indent > indent) { errors.push(`line ${l.n}: unexpected indentation`); i++; continue; }
      const after = l.raw.slice(l.indent + 1);
      const rest = after.trim();
      const restCol = l.indent + 1 + (after.length - after.replace(/^ +/, '').length);
      if (!rest) {
        i++;
        const j = nextContent(i);
        if (j < lines.length && lines[j].indent > indent) { i = j; out.push(parseNode(lines[j].indent)); } else out.push(null);
        continue;
      }
      if (!rest.startsWith('"') && !rest.startsWith("'") && !rest.startsWith('[') && !rest.startsWith('{') && splitKey(rest)) {
        lines[i] = { ...l, raw: ' '.repeat(restCol) + rest, indent: restCol, t: rest };
        out.push(parseMap(restCol));
        continue;
      }
      i++;
      out.push(inlineValue(rest, l, indent));
    }
    return out;
  }

  function parseMap(indent) {
    const out = {};
    for (;;) {
      i = nextContent(i);
      if (i >= lines.length) break;
      const l = lines[i];
      if (l.indent < indent) break;
      if (l.indent > indent) { errors.push(`line ${l.n}: unexpected indentation`); i++; continue; }
      if (isDash(l.t)) break;
      const kv = splitKey(l.t);
      if (!kv) { errors.push(`line ${l.n}: expected "key: value"`); i++; continue; }
      i++;
      if (Object.prototype.hasOwnProperty.call(out, kv.key)) errors.push(`line ${l.n}: duplicate key "${kv.key}"`);
      const rest = kv.rest;
      if (!rest || rest.startsWith('#')) {
        const j = nextContent(i);
        if (j < lines.length && (lines[j].indent > indent || (lines[j].indent === indent && isDash(lines[j].t)))) {
          i = j;
          out[kv.key] = parseNode(lines[j].indent);
        } else out[kv.key] = null;
        continue;
      }
      out[kv.key] = inlineValue(rest, l, indent);
    }
    return out;
  }

  const start = nextContent(0);
  if (start >= lines.length) return { value: {}, errors };
  i = start;
  const value = parseNode(lines[start].indent);
  const tail = nextContent(i);
  if (tail < lines.length) errors.push(`line ${lines[tail].n}: unexpected content`);
  return { value, errors };
}

const PLAIN_UNSAFE = /^[\s\-?:,[\]{}#&*!|>'"%@`]|[:]\s|\s#|:$|\s$|[\u0000-\u001f\u007f]/;

function yamlScalar(v) {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : JSON.stringify(String(v));
  const s = String(v);
  if (s === '') return '""';
  if (/^(true|false|null|yes|no|on|off|y|n|~)$/i.test(s) || /^[-+]?(\d[\d_]*(\.\d*)?|\.\d+)([eE][-+]?\d+)?$/.test(s) ||
    /^[0-9]/.test(s) || PLAIN_UNSAFE.test(s)) return JSON.stringify(s);
  return s;
}

const yamlKey = (k) => (/^[A-Za-z0-9_$][A-Za-z0-9_.$/-]*$/.test(k) ? k : JSON.stringify(k));
const flowItem = (v) => (typeof v === 'string' ? `'${v.replace(/'/g, "''")}'` : yamlScalar(v));

function foldable(s) {
  return s.length > 90 && !/\n|\t| {2}|^\s|\s$/.test(s);
}

function wrapWords(s, width) {
  const out = [];
  let line = '';
  for (const word of s.split(' ')) {
    if (line && line.length + 1 + word.length > width) { out.push(line); line = word; } else line = line ? `${line} ${word}` : word;
  }
  if (line) out.push(line);
  return out;
}

/**
 * Emit YAML for a plain object. `flowKeys` lists keys whose scalar arrays use `[a, b]`;
 * `quoteKeys` lists keys whose strings are always double-quoted (globs such as applyTo).
 */
export function stringifyYaml(obj, { indent = 0, flowKeys = [], quoteKeys = ['applyTo', 'paths', 'excludeAgent'] } = {}) {
  const pad = ' '.repeat(indent);
  const out = [];
  for (const [k, v] of Object.entries(obj || {})) {
    if (v === undefined) continue;
    const key = yamlKey(k);
    const scalar = quoteKeys.includes(k) ? (x) => (typeof x === 'string' ? JSON.stringify(x) : yamlScalar(x)) : yamlScalar;
    if (Array.isArray(v)) {
      if (!v.length) { out.push(`${pad}${key}: []`); continue; }
      const scalars = v.every((x) => x === null || typeof x !== 'object');
      if (scalars && flowKeys.includes(k)) { out.push(`${pad}${key}: [${v.map(flowItem).join(', ')}]`); continue; }
      out.push(`${pad}${key}:`);
      for (const item of v) {
        if (item && typeof item === 'object' && !Array.isArray(item)) {
          const inner = stringifyYaml(item, { indent: indent + 4, flowKeys, quoteKeys });
          if (!inner.length) { out.push(`${pad}  - {}`); continue; }
          out.push(`${pad}  - ${inner[0].slice(indent + 4)}`, ...inner.slice(1));
        } else out.push(`${pad}  - ${scalar(item)}`);
      }
      continue;
    }
    if (v && typeof v === 'object') {
      const inner = stringifyYaml(v, { indent: indent + 2, flowKeys, quoteKeys });
      out.push(inner.length ? `${pad}${key}:` : `${pad}${key}: {}`, ...inner);
      continue;
    }
    if (typeof v === 'string' && v.includes('\n')) {
      const body = v.replace(/\n$/, '');
      out.push(`${pad}${key}: ${v.endsWith('\n') ? '|' : '|-'}`, ...body.split('\n').map((l) => (l ? `${pad}  ${l}` : '')));
      continue;
    }
    if (typeof v === 'string' && foldable(v)) {
      out.push(`${pad}${key}: >-`, ...wrapWords(v, Math.max(40, 80 - indent - 2)).map((l) => `${pad}  ${l}`));
      continue;
    }
    out.push(`${pad}${key}: ${scalar(v)}`);
  }
  return out;
}

/** `---\n<yaml>\n---\n` for frontmatter data. */
export function stringifyFrontmatter(data, opts = {}) {
  const lines = stringifyYaml(data, opts);
  return `---\n${lines.join('\n')}${lines.length ? '\n' : ''}---\n`;
}

