/** Minimal TOML reader for config.toml: tables, dotted/quoted keys, strings, numbers, booleans, arrays, inline tables. */
export function parseTomlLite(text) {
  const root = {};
  let cur = root;
  const errors = [];
  const lines = stripBom(String(text ?? '')).split(/\r?\n/);
  const splitDotted = (s) => {
    const parts = [];
    let buf = '';
    let q = null;
    for (const c of s.trim()) {
      if (q) { if (c === q) q = null; else buf += c; continue; }
      if (c === '"' || c === "'") { q = c; continue; }
      if (c === '.') { parts.push(buf.trim()); buf = ''; continue; }
      buf += c;
    }
    parts.push(buf.trim());
    return parts;
  };
  const value = (src) => {
    let i = 0;
    const ws = () => { while (i < src.length && /[\s]/.test(src[i])) i++; };
    const node = () => {
      ws();
      const c = src[i];
      if (c === '"') {
        if (src.startsWith('"""', i)) { const end = src.indexOf('"""', i + 3); const s = src.slice(i + 3, end); i = end + 3; return s.replace(/^\n/, ''); }
        const r = parseDoubleQuoted(src.slice(i)); i = src.length - r.rest.length; return r.value;
      }
      if (c === "'") { const end = src.indexOf("'", i + 1); const s = src.slice(i + 1, end); i = end + 1; return s; }
      if (c === '[') {
        i++; const arr = [];
        for (;;) { ws(); if (src[i] === '#') { while (i < src.length && src[i] !== '\n') i++; continue; } if (src[i] === ']') { i++; return arr; } arr.push(node()); ws(); if (src[i] === ',') i++; }
      }
      if (c === '{') {
        i++; const obj = {};
        for (;;) {
          ws(); if (src[i] === '}') { i++; return obj; }
          let k = '';
          while (i < src.length && src[i] !== '=') k += src[i++];
          i++;
          const keys = splitDotted(k);
          let t = obj;
          for (const kk of keys.slice(0, -1)) t = (t[kk] ||= {});
          t[keys[keys.length - 1]] = node();
          ws(); if (src[i] === ',') i++;
        }
      }
      let s = '';
      while (i < src.length && !/[,\]}\s#]/.test(src[i])) s += src[i++];
      if (s === 'true') return true;
      if (s === 'false') return false;
      if (/^[-+]?\d[\d_]*(\.\d+)?([eE][-+]?\d+)?$/.test(s)) return Number(s.replace(/_/g, ''));
      return s;
    };
    return node();
  };
  for (let n = 0; n < lines.length; n++) {
    let line = lines[n].trim();
    if (!line || line.startsWith('#')) continue;
    if (line.startsWith('[[')) { cur = null; continue; }
    if (line.startsWith('[')) {
      const keys = splitDotted(line.slice(1, line.lastIndexOf(']')));
      cur = root;
      for (const k of keys) cur = (cur[k] && typeof cur[k] === 'object' ? cur[k] : (cur[k] = {}));
      continue;
    }
    if (!cur) continue;
    const eq = line.indexOf('=');
    if (eq < 0) { errors.push(`line ${n + 1}: expected key = value`); continue; }
    const keys = splitDotted(line.slice(0, eq));
    let src = line.slice(eq + 1).trim();
    const depth = (s) => { let d = 0; let q = null; for (const c of s) { if (q) { if (c === q) q = null; continue; } if (c === '"' || c === "'") q = c; else if (c === '[' || c === '{') d++; else if (c === ']' || c === '}') d--; } return d; };
    while ((depth(src) > 0 || (src.startsWith('"""') && src.indexOf('"""', 3) < 0)) && n + 1 < lines.length) src += '\n' + lines[++n];
    try {
      let t = cur;
      for (const k of keys.slice(0, -1)) t = (t[k] ||= {});
      t[keys[keys.length - 1]] = value(src);
    } catch (err) { errors.push(`line ${n + 1}: ${err.message}`); }
  }
  return { value: root, errors };
}

const tomlKey = (k) => (/^[A-Za-z0-9_-]+$/.test(k) ? k : JSON.stringify(k));
function tomlValue(v) {
  if (Array.isArray(v)) return `[${v.map(tomlValue).join(', ')}]`;
  if (v && typeof v === 'object') return `{ ${Object.entries(v).map(([k, x]) => `${tomlKey(k)} = ${tomlValue(x)}`).join(', ')} }`;
  if (typeof v === 'boolean' || typeof v === 'number') return String(v);
  return JSON.stringify(String(v));
}

const ENV_REF = /^\$\{([A-Za-z_][A-Za-z0-9_]*)(?::-[^}]*)?\}$/;
const INPUT_RE = /\$\{input:([A-Za-z0-9_.-]+)(?::[^}]*)?\}/g;
const inputEnvName = (id) => id.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '') || 'INPUT';

/** Parse an MCP config into `{ servers[{name, transport, command, args, env, cwd, url, headers, tools}], inputs[], dropped[], manual[] }`. */
export function parseMcpConfig(text, dialect, file = 'mcp config') {
  const dropped = [];
  const manual = [];
  const servers = [];
  if (dialect === 'toml') {
    const { value } = parseTomlLite(text);
    for (const [name, s] of Object.entries(value.mcp_servers || {})) {
      if (!s || typeof s !== 'object') continue;
      const env = { ...(s.env || {}) };
      for (const v of s.env_vars || []) { const n = typeof v === 'string' ? v : v?.name; if (n) env[n] = `\${${n}}`; }
      const headers = { ...(s.http_headers || {}) };
      for (const [h, envName] of Object.entries(s.env_http_headers || {})) headers[h] = `\${${envName}}`;
      if (s.bearer_token_env_var) headers.Authorization = `Bearer \${${s.bearer_token_env_var}}`;
      servers.push({ name, transport: s.url ? 'http' : 'stdio', command: s.command ?? null, args: (s.args || []).map(String), env,
        cwd: s.cwd ?? null, url: s.url ?? null, headers, tools: Array.isArray(s.enabled_tools) ? s.enabled_tools : null,
        enabled: s.enabled ?? null });
      for (const k of Object.keys(s)) {
        if (!['command', 'args', 'env', 'env_vars', 'cwd', 'url', 'http_headers', 'env_http_headers', 'bearer_token_env_var', 'enabled_tools', 'enabled'].includes(k)) {
          dropped.push({ file, field: `mcp_servers.${name}.${k}`, reason: 'Codex-only MCP setting' });
        }
      }
    }
    return { servers, inputs: [], dropped, manual };
  }
  let doc;
  try { doc = JSON.parse(stripBom(String(text))); } catch (err) { throw usageError(`${file}: not valid JSON (${err.message})`); }
  const inputs = Array.isArray(doc?.inputs) ? doc.inputs : [];
  const map = dialect === 'vscode' ? (doc?.servers || {}) : (doc?.mcpServers || (doc && !doc.servers && !doc.$schema ? doc : {}));
  const inputMap = new Map(inputs.map((x) => [String(x.id), x]));
  const fixInputs = (s) => (typeof s === 'string' ? s.replace(INPUT_RE, (_, id) => {
    const inp = inputMap.get(id);
    const envName = inputEnvName(id);
    manual.push(`Set the environment variable ${envName} before starting the host (it replaces the VS Code input "${id}"${inp?.password ? '; password inputs are never written to files' : ''}).`);
    return `\${${envName}}`;
  }) : s);
  for (const [name, s] of Object.entries(map)) {
    if (!s || typeof s !== 'object') continue;
    const t = String(s.type || (s.url ? 'http' : 'stdio')).toLowerCase();
    const transport = t === 'sse' ? 'sse' : (t === 'http' || t === 'streamable-http' || t === 'streamablehttp') ? 'http' : 'stdio';
    const env = {};
    for (const [k, v] of Object.entries(s.env || {})) env[k] = fixInputs(String(v));
    const headers = {};
    for (const [k, v] of Object.entries(s.headers || {})) headers[k] = fixInputs(String(v));
    servers.push({ name, transport, command: s.command ?? null, args: (s.args || []).map((a) => fixInputs(String(a))), env, cwd: s.cwd ?? null,
      url: s.url ? fixInputs(String(s.url)) : null, headers, tools: Array.isArray(s.tools) ? s.tools : null });
    const known = ['type', 'command', 'args', 'env', 'cwd', 'url', 'headers', 'tools'];
    for (const k of Object.keys(s)) {
      if (known.includes(k)) continue;
      dropped.push({ file, field: `${dialect === 'vscode' ? 'servers' : 'mcpServers'}.${name}.${k}`, value: typeof s[k] === 'string' ? s[k] : undefined,
        reason: k === 'envFile' ? 'VS Code-only; load the env file yourself or set the variables' : 'host-specific MCP field' });
    }
  }
  if (dialect === 'vscode' && inputs.length) {
    for (const inp of inputs) if (![...JSON.stringify(map).matchAll(INPUT_RE)].some((m) => m[1] === String(inp.id))) dropped.push({ file, field: `inputs.${inp.id}`, reason: 'unused VS Code input' });
  }
  return { servers, inputs, dropped, manual };
}

/**
 * Render servers for a target: 'claude' (.mcp.json), 'copilot' (.github/mcp.json), 'codex'
 * (config.toml text), 'agent-plugins' (plugin mcp.json). Returns `{ doc | text, dropped[], manual[] }`.
 */
export function renderMcpConfig(servers, target, { file = 'mcp' } = {}) {
  const dropped = [];
  const manual = [];
  if (target === 'codex') {
    const blocks = [];
    for (const s of servers) {
      const lines = [`[mcp_servers.${tomlKey(s.name)}]`];
      if (s.transport === 'sse') dropped.push({ file, field: `${s.name}.type`, value: 'sse', reason: 'Codex supports stdio and streamable HTTP; check that the endpoint speaks streamable HTTP' });
      if (s.transport === 'stdio') {
        lines.push(`command = ${tomlValue(s.command || '')}`);
        if (s.args.length) lines.push(`args = ${tomlValue(s.args)}`);
        const literal = {};
        const forward = [];
        for (const [k, v] of Object.entries(s.env || {})) {
          const m = ENV_REF.exec(v);
          if (m && m[1] === k) forward.push(k);
          else if (/\$\{/.test(v)) manual.push(`Codex does not expand "${v}" in env; set ${k} for ${s.name} in the environment Codex starts from.`);
          else literal[k] = v;
        }
        if (Object.keys(literal).length) lines.push(`env = ${tomlValue(literal)}`);
        if (forward.length) lines.push(`env_vars = ${tomlValue(forward)}`);
        if (s.cwd) lines.push(`cwd = ${tomlValue(s.cwd)}`);
      } else {
        lines.push(`url = ${tomlValue(s.url || '')}`);
        const literal = {};
        const envHeaders = {};
        for (const [h, v] of Object.entries(s.headers || {})) {
          const bearer = /^Bearer \$\{([A-Za-z_][A-Za-z0-9_]*)\}$/.exec(v);
          const ref = ENV_REF.exec(v);
          if (/^authorization$/i.test(h) && bearer) lines.push(`bearer_token_env_var = ${tomlValue(bearer[1])}`);
          else if (ref) envHeaders[h] = ref[1];
          else if (/\$\{/.test(v)) manual.push(`Header ${h} of ${s.name} mixes text and a variable; Codex supports whole-value env_http_headers only.`);
          else literal[h] = v;
        }
        if (Object.keys(literal).length) lines.push(`http_headers = ${tomlValue(literal)}`);
        if (Object.keys(envHeaders).length) lines.push(`env_http_headers = ${tomlValue(envHeaders)}`);
      }
      if (s.tools && !(s.tools.length === 1 && s.tools[0] === '*')) lines.push(`enabled_tools = ${tomlValue(s.tools)}`);
      if (s.enabled === false) lines.push('enabled = false');
      blocks.push({ name: s.name, text: lines.join('\n') + '\n' });
    }
    return { text: blocks.map((b) => b.text).join('\n'), blocks, dropped, manual };
  }
  const out = {};
  for (const s of servers) {
    const e = {};
    if (target === 'agent-plugins') {
      e.type = s.transport === 'http' ? 'streamable-http' : s.transport;
      if (s.transport === 'stdio') {
        let command = s.command || '';
        let args = [...s.args];
        if (/\s/.test(command)) { const parts = splitSimpleCommand(command); if (parts) { command = parts[0]; args = [...parts.slice(1), ...args]; } }
        e.command = command;
        if (args.length) e.args = args;
        const env = {};
        for (const [k, v] of Object.entries(s.env || {})) {
          if (/\$\{(?!PLUGIN_ROOT\}|PLUGIN_DATA\})/.test(v)) { dropped.push({ file, field: `${s.name}.env.${k}`, value: v, reason: 'Agent Plugins expands only ${PLUGIN_ROOT} and ${PLUGIN_DATA}; users must set this variable themselves' }); continue; }
          env[k] = v;
        }
        if (Object.keys(env).length) e.env = env;
        if (s.cwd) {
          if (/^(\.\/|\$\{PLUGIN_ROOT\}|\$\{PLUGIN_DATA\})/.test(s.cwd)) e.cwd = s.cwd;
          else dropped.push({ file, field: `${s.name}.cwd`, value: s.cwd, reason: 'Agent Plugins cwd must start with ./, ${PLUGIN_ROOT} or ${PLUGIN_DATA}' });
        }
      } else {
        e.url = s.url;
        const headers = {};
        for (const [h, v] of Object.entries(s.headers || {})) {
          if (/\$\{/.test(v)) { dropped.push({ file, field: `${s.name}.headers.${h}`, reason: 'Agent Plugins never expands variables in headers and forbids secrets there; the host must handle authorization' }); continue; }
          headers[h] = v;
        }
        if (Object.keys(headers).length) e.headers = headers;
      }
      if (s.tools) dropped.push({ file, field: `${s.name}.tools`, reason: 'Agent Plugins mcp.json has no tools allow-list' });
    } else {
      e.type = target === 'copilot' ? (s.transport === 'stdio' ? 'local' : s.transport) : s.transport;
      if (s.transport === 'stdio') {
        e.command = s.command || '';
        if (s.args.length) e.args = s.args;
        if (Object.keys(s.env || {}).length) e.env = s.env;
        if (s.cwd) dropped.push({ file, field: `${s.name}.cwd`, value: s.cwd, reason: `${target === 'copilot' ? 'Copilot' : 'Claude Code'} .mcp.json servers have no documented cwd` });
      } else {
        e.url = s.url;
        if (Object.keys(s.headers || {}).length) e.headers = s.headers;
      }
      if (target === 'copilot') e.tools = s.tools && s.tools.length ? s.tools : ['*'];
      else if (s.tools && !(s.tools.length === 1 && s.tools[0] === '*')) dropped.push({ file, field: `${s.name}.tools`, value: s.tools.join(','), reason: 'Claude Code .mcp.json has no tools allow-list; use permissions instead' });
      if (e.url && /^http:\/\//i.test(e.url) && !/^http:\/\/(localhost|127\.|\[::1\])/i.test(e.url)) manual.push(`${s.name}: use https for non-loopback MCP URLs.`);
    }
    out[s.name] = e;
  }
  const doc = target === 'agent-plugins'
    ? { $schema: 'https://agent-plugins.org/schemas/1.0.0/mcp.schema.json', mcpServers: out }
    : { mcpServers: out };
  return { doc, dropped, manual };
}

function mergeMcpJson(existingText, doc) {
  const cur = existingText.trim() ? JSON.parse(stripBom(existingText)) : {};
  if (!cur || typeof cur !== 'object' || Array.isArray(cur)) throw new Error('existing file is not a JSON object');
  cur.mcpServers = cur.mcpServers && typeof cur.mcpServers === 'object' ? cur.mcpServers : {};
  for (const [name, s] of Object.entries(doc.mcpServers)) if (!(name in cur.mcpServers)) cur.mcpServers[name] = s;
  return JSON.stringify(cur, null, 2) + '\n';
}

function mergeToml(existingText, blocks) {
  const { value } = parseTomlLite(existingText);
  const have = value.mcp_servers || {};
  let text = existingText;
  for (const b of blocks) {
    if (b.name in have) continue;
    text += (text && !text.endsWith('\n') ? '\n' : '') + (text.trim() ? '\n' : '') + b.text;
  }
  return text;
}

