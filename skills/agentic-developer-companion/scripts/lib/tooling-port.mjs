function listSkillFiles(absDir) {
  const out = [];
  const walk = (d, rel) => {
    let entries = [];
    try { entries = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
    for (const e of entries.sort((a, b) => (a.name < b.name ? -1 : 1))) {
      if (['.git', 'node_modules', '.DS_Store', 'results'].includes(e.name)) continue;
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) walk(path.join(d, e.name), r);
      else if (e.isFile()) out.push(r);
    }
  };
  walk(absDir, '');
  return out;
}

function convertSkill(src, cls, targets) {
  const outputs = [];
  const dropped = [];
  const manual = [];
  const notes = [];
  const absDir = path.dirname(src.abs);
  const fm = readFrontmatter(src.text);
  const name = asText(fm.data.name) || path.basename(absDir);
  if (name !== path.basename(absDir)) manual.push(`Skill name "${name}" differs from its directory "${path.basename(absDir)}"; VS Code silently skips such skills.`);
  const files = listSkillFiles(absDir);
  for (const host of targets) {
    if (cls.hosts.includes(host)) { notes.push(`${host}: already loads ${cls.dir}`); continue; }
    const dir = `${SKILL_DIRS[host]}/${name}`;
    for (const f of files) {
      outputs.push({ path: `${dir}/${f}`, content: fs.readFileSync(path.join(absDir, f)), host, kind: 'skill' });
    }
    const allowed = SKILL_HOST_FIELDS[host];
    if (allowed) {
      for (const k of Object.keys(fm.data)) if (!allowed.includes(k)) dropped.push({ file: src.rel, field: k, reason: `${host} ignores this SKILL.md field (copied unchanged)` });
    }
    if (host !== 'claude' && CLAUDE_PLACEHOLDERS.test(fm.body)) manual.push(`${dir}/SKILL.md uses Claude-only placeholders or !\`cmd\` blocks; ${host} does not expand them.`);
    if (host === 'codex' && asBool(fm.data['disable-model-invocation']) === true && !files.includes('agents/openai.yaml')) {
      outputs.push({ path: `${dir}/agents/openai.yaml`, content: renderOpenAiYaml({ name, description: asText(fm.data.description), implicit: false }), host, kind: 'skill' });
      notes.push('codex: disable-model-invocation became policy.allow_implicit_invocation: false in agents/openai.yaml');
    }
    manual.push(`Keep ${dir} in sync with ${cls.dir}: re-run \`tooling port ${cls.dir} --to ${host} --force\` after editing the source.`);
  }
  return { outputs, dropped, manual, notes };
}

function convertAgent(src, cls, targets) {
  const outputs = [];
  const dropped = [];
  const manual = [];
  const notes = [];
  const ir = parseAgent(src.text, cls.host, src.rel);
  for (const e of ir.errors) manual.push(`${src.rel}: frontmatter: ${e}`);
  for (const host of targets) {
    if (host === cls.host) { notes.push(`${host}: native`); continue; }
    if (host === 'codex') {
      const name = toSkillName(ir.name);
      const dir = `${CODEX_ONLY_SKILLS_DIR}/${name}`;
      outputs.push({ path: `${dir}/SKILL.md`, content: skillFrontmatter({ name, description: ir.description, host: 'codex' }) + '\n' + ir.body, host, kind: 'skill' });
      outputs.push({ path: `${dir}/agents/openai.yaml`, content: renderOpenAiYaml({ name, description: ir.description, implicit: ir.disableModelInvocation !== true }), host, kind: 'skill' });
      if (ir.tools) dropped.push({ file: src.rel, field: 'tools', value: ir.tools.join(', '), reason: 'Codex skills have no tool restriction; state limits in the body' });
      if (ir.model) dropped.push({ file: src.rel, field: 'model', value: ir.model, reason: 'Codex skills have no model field' });
      for (const k of Object.keys(ir.extra)) dropped.push({ file: src.rel, field: k, reason: 'no Codex equivalent' });
      manual.push(`Codex has no custom agent files: ${ir.name} became the skill ${dir} (invoke it as $${name}). The .codex/agents/<name>.toml role format is unverified and was not generated.`);
      continue;
    }
    if (host === 'copilot' && cls.host === 'claude') notes.push('copilot: Copilot CLI also reads .claude/agents directly');
    const r = renderAgent(ir, host, { file: src.rel });
    outputs.push({ path: r.path, content: r.content, host, kind: 'agent' });
    dropped.push(...r.dropped);
    manual.push(...r.manual);
  }
  return { outputs, dropped, manual, notes };
}

const HOOK_TARGET = { copilot: null, claude: '.claude/settings.json', codex: '.codex/hooks.json' };

function convertHooks(src, cls, targets, { inPlace = false } = {}) {
  const parsed = parseHookConfig(src.text, cls.host, src.rel);
  const outputs = [];
  const dropped = [...parsed.dropped];
  const manual = [];
  const notes = [...parsed.notes];
  for (const host of targets) {
    if (host === cls.host && !inPlace) { notes.push(`${host}: native`); continue; }
    const r = renderHookConfig(parsed.entries, host, { file: src.rel });
    dropped.push(...r.dropped);
    manual.push(...r.manual);
    notes.push(...r.notes);
    let target = HOOK_TARGET[host];
    if (host === 'copilot') {
      const stem = inPlace ? path.posix.basename(src.rel, '.json')
        : cls.host === 'claude' ? 'claude-settings' : cls.host === 'codex' ? 'codex-hooks' : path.posix.basename(src.rel, '.json');
      target = inPlace ? src.rel : `.github/hooks/${stem}.json`;
    }
    const content = JSON.stringify(r.doc, null, 2) + '\n';
    if (inPlace && host === cls.host) outputs.push({ path: target, content, host, kind: 'hooks', replace: true });
    else outputs.push({ path: target, content, merge: (cur) => mergeHooksJson(cur, r.doc), host, kind: 'hooks' });
    if (host === 'claude' && cls.host === 'copilot') manual.push('Copilot CLI and VS Code also run hooks from .claude/settings.json: remove the original .github/hooks file for local sessions or expect the hook to run twice (the cloud agent reads only .github/hooks).');
    if (host === 'codex') manual.push('Codex runs repository hooks only after the project is trusted and each hook is reviewed once in /hooks.');
  }
  return { outputs, dropped, manual, notes };
}

const MCP_TARGET = { claude: '.mcp.json', copilot: '.github/mcp.json', codex: '.codex/config.toml' };

function convertMcp(src, cls, targets) {
  const parsed = parseMcpConfig(src.text, cls.dialect, src.rel);
  const outputs = [];
  const dropped = [...parsed.dropped];
  const manual = [...new Set(parsed.manual)];
  const notes = [];
  for (const host of targets) {
    if (host === 'claude' && src.rel.endsWith('.mcp.json') && cls.dialect === 'mcpServers') { notes.push('claude: native'); continue; }
    if (host === 'copilot' && (src.rel === '.mcp.json' || src.rel === '.github/mcp.json')) { notes.push('copilot: Copilot CLI reads .mcp.json and .github/mcp.json natively'); continue; }
    if (host === 'codex' && cls.dialect === 'toml') { notes.push('codex: native'); continue; }
    const r = renderMcpConfig(parsed.servers, host, { file: src.rel });
    dropped.push(...r.dropped);
    manual.push(...r.manual);
    if (host === 'codex') {
      outputs.push({ path: MCP_TARGET.codex, content: r.text, merge: (cur) => mergeToml(cur, r.blocks), host, kind: 'mcp' });
      manual.push('Codex reads a repository .codex/config.toml only for trusted projects; or add the [mcp_servers] tables to ~/.codex/config.toml.');
    } else {
      outputs.push({ path: MCP_TARGET[host], content: JSON.stringify(r.doc, null, 2) + '\n', merge: (cur) => mergeMcpJson(cur, r.doc), host, kind: 'mcp' });
    }
    if (host === 'copilot') {
      const cloud = { mcpServers: Object.fromEntries(Object.entries(renderMcpConfig(parsed.servers, 'copilot').doc.mcpServers)) };
      manual.push(`Copilot cloud agent reads MCP servers only from repository Settings > Copilot > MCP servers (secrets as COPILOT_MCP_* agent secrets); paste: ${JSON.stringify(cloud)}`);
    }
  }
  if (parsed.servers.some((s) => Object.values(s.env || {}).some((v) => v && !/\$\{/.test(v) && /(token|secret|key|password)/i.test(v)))) {
    manual.push('An env value looks like a literal credential; reference an environment variable instead.');
  }
  return { outputs, dropped, manual, notes };
}

// ---------------------------------------------------------------------------
// Applying outputs: create freely, never modify an existing file without --force.

const sameContent = (a, b) => (Buffer.isBuffer(a) || Buffer.isBuffer(b) ? Buffer.from(a).equals(Buffer.from(b)) : a === b);

/**
 * Write planned outputs under `outRoot`. Existing files are left alone unless `force`
 * (then merged when the output has a merge function, overwritten otherwise, with a backup
 * under `<state>/tooling/backups/<ts>/`). Returns `{ written[], skipped[], backups[] }`.
 */
export function applyOutputs(outputs, { outRoot, dryRun = false, force = false, backupDir = null } = {}) {
  const written = [];
  const skipped = [];
  const backups = [];
  const seen = new Map();
  for (const o of outputs) {
    if (seen.has(o.path)) {
      const prev = seen.get(o.path);
      if (o.merge && typeof prev.content === 'string') { prev.content = o.merge(prev.content); continue; }
      continue;
    }
    seen.set(o.path, { ...o });
  }
  let backupRoot = null;
  for (const o of seen.values()) {
    const abs = path.join(outRoot, ...o.path.split('/'));
    const exists = fs.existsSync(abs);
    let next = o.content;
    let action = 'create';
    if (exists) {
      const cur = fs.readFileSync(abs);
      const curText = cur.toString('utf8');
      action = o.merge && !o.replace ? 'merge' : 'overwrite';
      if (o.merge && !o.replace) {
        try { next = o.merge(curText); } catch (err) { skipped.push({ path: o.path, reason: `cannot merge: ${err.message}`, host: o.host }); continue; }
      }
      if (sameContent(cur, typeof next === 'string' ? next : next)) { written.push({ path: o.path, action: 'unchanged', host: o.host, kind: o.kind }); continue; }
      if (!force && !o.replace) { skipped.push({ path: o.path, reason: 'exists (use --force to ' + action + ')', planned: action, host: o.host, kind: o.kind }); continue; }
      if (!dryRun && backupDir) {
        backupRoot ||= backupDir();
        if (backupRoot) {
          const b = path.join(backupRoot, ...o.path.split('/'));
          ensureDir(path.dirname(b));
          fs.writeFileSync(b, cur);
          backups.push(toPosix(b));
        }
      }
    }
    if (!dryRun) writeFileAtomic(abs, next);
    written.push({ path: o.path, action: dryRun ? `would-${action}` : action, host: o.host, kind: o.kind, bytes: Buffer.byteLength(next) });
  }
  return { written, skipped, backups };
}

/** Lazy backup directory inside the state dir (created only when a backup is needed). */
export function backupDirFactory(ctx, root) {
  return () => {
    try {
      const info = prepareStateDir({ cwd: root, stateDirOption: ctx?.stateDirOption ?? null }, { create: true });
      return ensureDir(path.join(statePaths(info.dir).tooling, 'backups', stamp()));
    } catch {
      return null;
    }
  };
}

