// Command lines: split simple commands into argv; render argv per shell.

const VAR_RE = /\$\{([A-Za-z_][A-Za-z0-9_]*)\}|\$([A-Za-z_][A-Za-z0-9_]*)/g;

/**
 * argv for a command line that needs no shell (no pipes, redirects, globs, chaining), or
 * null. `$VAR` and `${VAR}` placeholders are kept as `${VAR}` in the tokens.
 */
export function splitSimpleCommand(line) {
  const s = String(line ?? '').trim();
  if (!s || /[\r\n]/.test(s)) return null;
  const out = [];
  let cur = '';
  let quote = null;
  let started = false;
  for (let k = 0; k < s.length; k++) {
    const c = s[k];
    if (quote === "'") { if (c === "'") quote = null; else cur += c; continue; }
    if (c === '$') {
      VAR_RE.lastIndex = k;
      const m = VAR_RE.exec(s);
      if (!m || m.index !== k) return null;
      cur += `\${${m[1] || m[2]}}`;
      k += m[0].length - 1;
      started = true;
      continue;
    }
    if (quote === '"') { if (c === '"') quote = null; else if (c === '`' || c === '\\') return null; else cur += c; continue; }
    if (c === "'" || c === '"') { quote = c; started = true; continue; }
    if (c === ' ' || c === '\t') { if (started) { out.push(cur); cur = ''; started = false; } continue; }
    if (/[|&;<>()`\\*?[\]{}~!#%^]/.test(c)) return null;
    cur += c;
    started = true;
  }
  if (quote) return null;
  if (started) out.push(cur);
  if (!out.length || /^[A-Za-z_][A-Za-z0-9_]*=/.test(out[0])) return null;
  return out;
}

const SAFE_TOKEN = /^[A-Za-z0-9_\-+=.,/:@]+$/;

/** argv → POSIX sh command line (`${VAR}` placeholders stay expandable). */
export function joinPosix(argv) {
  return argv.map((a) => {
    const s = String(a);
    if (s && SAFE_TOKEN.test(s)) return s;
    if (/\$\{[A-Za-z_][A-Za-z0-9_]*\}/.test(s)) {
      const parts = s.split(/(\$\{[A-Za-z_][A-Za-z0-9_]*\})/);
      return '"' + parts.map((p, idx) => (idx % 2 ? p : p.replace(/["\\$`]/g, '\\$&'))).join('') + '"';
    }
    return "'" + s.replace(/'/g, "'\\''") + "'";
  }).join(' ');
}

/** argv → PowerShell command line (`${VAR}` → `$env:VAR`). */
export function joinPowerShell(argv) {
  const tok = (a) => {
    const s = String(a);
    if (s && SAFE_TOKEN.test(s) && !s.startsWith('@')) return { text: s, quoted: false };
    if (/\$\{[A-Za-z_][A-Za-z0-9_]*\}/.test(s)) {
      const parts = s.split(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/);
      return { text: '"' + parts.map((p, idx) => (idx % 2 ? `$env:${p}` : p.replace(/[`"$]/g, '`$&'))).join('') + '"', quoted: true };
    }
    return { text: "'" + s.replace(/'/g, "''") + "'", quoted: true };
  };
  const toks = argv.map(tok);
  if (/^-/.test(String(argv[0]))) toks[0] = { text: `'${String(argv[0])}'`, quoted: true };
  return (toks[0].quoted ? '& ' : '') + toks.map((t) => t.text).join(' ');
}

/** argv → cmd.exe command line (`${VAR}` → `%VAR%`). */
export function joinCmd(argv) {
  return argv.map((a) => {
    const s = String(a).replace(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g, '%$1%');
    if (s && /^[A-Za-z0-9_\-+=.,/:@%\\]+$/.test(s)) return s;
    return '"' + s.replace(/"/g, '""') + '"';
  }).join(' ');
}

