// port() and the CLI command

function resolveTargets(to, fromHost) {
  if (!to || to === 'all') return HOSTS.filter((h) => h !== fromHost);
  const list = String(to).split(',').map((s) => s.trim()).filter(Boolean);
  for (const h of list) if (!HOSTS.includes(h)) throw usageError(`--to must be copilot, claude, codex or all (got "${h}")`);
  return [...new Set(list)];
}

function locateSource(root, cwd, p) {
  const abs = path.resolve(cwd, p);
  if (!fs.existsSync(abs)) throw usageError(`not found: ${toPosix(p)}`);
  let file = abs;
  if (fs.statSync(abs).isDirectory()) {
    if (fs.existsSync(path.join(abs, 'SKILL.md'))) file = path.join(abs, 'SKILL.md');
    else throw usageError(`${toPosix(p)} is a directory without SKILL.md; pass a file (or a skill directory)`);
  }
  const rel = relPosix(root, file) ?? toPosix(file);
  return { abs: file, rel };
}

const CONVERTERS = {
  instructions: convertInstructions, scoped: convertScoped, agent: convertAgent, prompt: convertPromptLike, command: convertPromptLike,
  chatmode: convertChatmode, skill: convertSkill, hooks: convertHooks, mcp: convertMcp,
};

/**
 * Translate one tooling artifact. `path` is relative to `cwd` (default: root); targets are
 * written under `out` (default: the repository root) at each host's canonical location.
 * Returns `{ source, targets, written[], skipped[], dropped_fields[], manual_steps[], notes[] }`.
 */
export async function port({ path: srcPath, from = null, to = 'all', out = null, root = null, cwd = null, dryRun = false, force = false,
  inPlace = false, backupDir = null } = {}) {
  await loadFrontmatterLib();
  if (!srcPath) throw usageError('tooling port needs a path (e.g. tooling port .github/agents/reviewer.agent.md --to claude)');
  const base = cwd || root || process.cwd();
  const rootDir = root || repoRoot(base) || base;
  const src = locateSource(rootDir, base, srcPath);
  src.text = readText(src.abs, '');
  const cls = classifyArtifact(src.rel);
  if (!cls) throw usageError(`cannot tell which tooling format ${src.rel} is; pass a file at its host location (see references/tooling-port.md)`);
  if (from && from !== cls.host && !(cls.host === 'portable' || cls.host === 'vscode')) {
    throw usageError(`${src.rel} is a ${cls.host} ${cls.kind} file, not ${from}`);
  }
  const fromHost = cls.host === 'portable' && from ? from : cls.host;
  const convert = CONVERTERS[cls.kind];
  if (!convert) throw usageError(`${cls.kind} files cannot be ported (use tooling plugin for plugin manifests)`);
  const targets = inPlace ? [cls.host] : resolveTargets(to, HOSTS.includes(fromHost) ? fromHost : null);
  const conv = cls.kind === 'hooks' ? convert(src, cls, targets, { inPlace }) : convert(src, cls, targets, { root: rootDir });
  const outRoot = out ? path.resolve(base, out) : rootDir;
  const applied = applyOutputs(conv.outputs, { outRoot, dryRun, force, backupDir });
  return {
    source: { path: src.rel, kind: cls.kind, host: fromHost },
    targets,
    out: toPosix(path.relative(rootDir, outRoot) || '.'),
    dry_run: Boolean(dryRun),
    written: applied.written,
    skipped: applied.skipped,
    backups: applied.backups,
    dropped_fields: conv.dropped,
    manual_steps: [...new Set(conv.manual)],
    notes: [...new Set(conv.notes)],
  };
}

/** Built-in migrations (§11.6); each maps to a port with a fixed source kind and target. */
export const MIGRATIONS = Object.freeze({
  'prompt-to-skill': { kinds: ['prompt'], host: 'copilot', describe: '.github/prompts/*.prompt.md -> skill with disable-model-invocation: true' },
  'chatmode-to-agent': { kinds: ['chatmode'], host: 'copilot', describe: '.github/chatmodes/*.chatmode.md -> .github/agents/*.agent.md' },
  'claude-commands-to-skills': { kinds: ['command'], host: 'claude', describe: '.claude/commands/**/*.md -> .claude/skills/<name>/SKILL.md' },
  'vscode-mcp-to-mcp-json': { kinds: ['mcp'], host: 'claude', dialect: 'vscode', describe: '.vscode/mcp.json (servers, ${input:}) -> .mcp.json (mcpServers, ${VAR})' },
  'copilot-hooks-to-camel': { kinds: ['hooks'], host: 'copilot', inPlace: true, describe: 'legacy or PascalCase .github/hooks/*.json -> version 1 camelCase with bash + powershell' },
});

/** Expand a migration source (a file or, for commands, a directory) into the files to migrate. */
export function migrationSources(kind, root, cwd, p) {
  const spec = MIGRATIONS[kind];
  if (!spec) throw usageError(`unknown migration "${kind}" (expected ${Object.keys(MIGRATIONS).join(', ')})`);
  const abs = path.resolve(cwd, p);
  if (!fs.existsSync(abs)) throw usageError(`not found: ${toPosix(p)}`);
  const files = fs.statSync(abs).isDirectory()
    ? listSkillFiles(abs).map((f) => path.join(abs, f)).filter((f) => { const c = classifyArtifact(relPosix(root, f) ?? ''); return c && spec.kinds.includes(c.kind); })
    : [abs];
  const out = [];
  for (const f of files) {
    const rel = relPosix(root, f) ?? toPosix(f);
    const cls = classifyArtifact(rel);
    if (!cls || !spec.kinds.includes(cls.kind) || (spec.dialect && cls.dialect !== spec.dialect)) {
      throw usageError(`${rel} is not a source for ${kind} (${spec.describe})`);
    }
    out.push(rel);
  }
  if (!out.length) throw usageError(`no ${spec.describe.split(' ->')[0]} files under ${toPosix(p)}`);
  return out;
}

/** Run a migration; returns the merged port results plus `{ migration, sources[] }`. */
export async function migrate(kind, { path: p, root, cwd = null, host = null, dryRun = false, force = false, backupDir = null } = {}) {
  const spec = MIGRATIONS[kind];
  const base = cwd || root;
  const sources = migrationSources(kind, root, base, p);
  const merged = { migration: kind, describe: spec.describe, sources, written: [], skipped: [], backups: [], dropped_fields: [], manual_steps: [], notes: [] };
  for (const rel of sources) {
    const r = await port({ path: rel, root, cwd: root, to: host || spec.host, dryRun, force: force || Boolean(spec.inPlace), inPlace: Boolean(spec.inPlace), backupDir });
    for (const k of ['written', 'skipped', 'backups', 'dropped_fields', 'manual_steps', 'notes']) merged[k].push(...r[k]);
  }
  merged.manual_steps = [...new Set(merged.manual_steps)];
  merged.notes = [...new Set(merged.notes)];
  if (kind === 'copilot-hooks-to-camel') {
    merged.manual_steps.push('camelCase events send camelCase payloads (toolName, toolArgs as a JSON string) instead of the snake_case ones PascalCase events got; update the handler.');
  }
  return merged;
}

export const PORT_OPTIONS = Object.freeze({
  from: { type: 'string' },
  to: { type: 'string' },
  out: { type: 'string' },
  force: { type: 'boolean' },
});

export const portCommand = defineCommand({
  name: 'tooling port',
  usage: 'tooling port <path> [--to copilot|claude|codex|all] [--from host] [--out dir] [--force] [--dry-run]',
  options: PORT_OPTIONS,
  async run(ctx, values, positionals) {
    if (!positionals[0]) throw usageError('tooling port needs a path');
    if (positionals.length > 1) throw usageError('tooling port takes one path');
    const root = repoRoot(ctx.cwd) || ctx.cwd;
    prepareStateDir({ ...ctx, cwd: root }, { create: false });
    const res = await port({ path: positionals[0], from: values.from || null, to: values.to || 'all', out: values.out || null, root, cwd: ctx.cwd,
      dryRun: ctx.dryRun, force: Boolean(values.force), backupDir: backupDirFactory(ctx, root) });
    const n = res.written.filter((w) => w.action !== 'unchanged').length;
    return {
      result: res,
      exit: 0,
      summary: `${res.source.kind} ${res.source.path} -> ${res.targets.join(', ')}: ${n} file(s) ${ctx.dryRun ? 'planned' : 'written'}, ${res.skipped.length} skipped, ${res.dropped_fields.length} dropped field(s), ${res.manual_steps.length} manual step(s)`,
    };
  },
});
